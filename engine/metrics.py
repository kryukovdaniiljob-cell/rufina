"""Категорийный движок: факт-таблица, иерархия, GMROI, OOS, рабочие списки."""
from __future__ import annotations
import os, json, datetime as dt
import numpy as np
import pandas as pd

from io_excel import (читать_лист, проверить_колонки, очистить, в_число,
                      из_серийной_даты, ОшибкаДанных,
                      листы_файла, читать_лист_позиционно)

МЕСЯЦЫ = ["Январь","Февраль","Март","Апрель","Май","Июнь","Июль","Август",
          "Сентябрь","Октябрь","Ноябрь","Декабрь"]
НОМЕР_МЕСЯЦА = {m: i + 1 for i, m in enumerate(МЕСЯЦЫ)}
# Офисы заполняются из выгрузки при загрузке (см. определить_офисы).
# Раньше здесь был вшитый список из четырёх городов: любой другой офис
# попадал в «Прочие» и выпадал из расчёта дефицита.
ОСНОВНЫЕ_ОФИСЫ: list[str] = []


# ------------------------------------------------------------------ измерения
def _цел(v) -> str:
    """Число с неразрывными пробелами — для текста внутри ячейки."""
    try:
        return format(int(round(float(v))), ",d").replace(",", chr(160))
    except (TypeError, ValueError):
        return "0"


def определить_офисы(d: dict, cfg: dict, лог) -> list[str]:
    """Офисы берём из самой выгрузки, а не из кода.

    Настройка «периметр.офисы» позволяет сузить список, если часть
    филиалов считать не надо. По умолчанию берутся все, что есть."""
    global ОСНОВНЫЕ_ОФИСЫ
    задано = (cfg.get("периметр", {}) or {}).get("офисы") or []
    if задано:
        ОСНОВНЫЕ_ОФИСЫ = [str(x) for x in задано]
        лог("   Офисы из настроек: %s" % ", ".join(ОСНОВНЫЕ_ОФИСЫ))
        return ОСНОВНЫЕ_ОФИСЫ
    из_данных = set()
    for ключ in ("продажи", "сток_год", "сток_тек"):
        t = d.get(ключ)
        if t is not None and "Офис" in t.columns:
            из_данных |= {str(x).strip() for x in t["Офис"].dropna().unique()
                          if str(x).strip()}
    ОСНОВНЫЕ_ОФИСЫ = sorted(из_данных)
    лог("   Офисы из выгрузки: %d - %s"
        % (len(ОСНОВНЫЕ_ОФИСЫ), ", ".join(ОСНОВНЫЕ_ОФИСЫ[:6])
           + (" и ещё %d" % (len(ОСНОВНЫЕ_ОФИСЫ) - 6) if len(ОСНОВНЫЕ_ОФИСЫ) > 6 else "")))
    if not ОСНОВНЫЕ_ОФИСЫ:
        лог("   ! В выгрузке нет колонки «Офис» - расчёт дефицита будет пустым")
    return ОСНОВНЫЕ_ОФИСЫ


def офис(s) -> str:
    s = str(s)
    for k in ОСНОВНЫЕ_ОФИСЫ:
        if s.startswith(k):
            return k
    return "Прочие"


def тип_склада(s) -> str:
    s = str(s)
    if "Cash&Carry" in s:            return "Cash&Carry"
    if "Витрина" in s:               return "Витрина"
    if s.startswith(("РРЦ", "ФРЦ")): return "РЦ"
    if "Основной склад" in s:        return "Основной"
    return "Прочее"


def филиал(s) -> str:
    """Филиал = город из имени офиса. Раньше города были вшиты в код,
    и новый филиал молча попадал бы в «Прочее»."""
    o = офис(s)
    if not o or o == "Прочие":
        return "Прочее"
    return "Филиал РТГ " + o.split()[0]


# ------------------------------------------------------------------ загрузка
def загрузить(пути: dict, лог) -> dict:
    if "сквозная" not in пути:
        raise ОшибкаДанных(
            "Не найден файл сквозной аналитики - без него расчёт невозможен." + chr(10) +
            "Положите его в папку 1_ВХОД. Опознаётся по листам: Каталог, Продажи 2026, Сток 2026, Матрица РТГ 2026.")
    S = пути["сквозная"]
    d = {}
    пропало = []

    def лист(тип, путь, имя, hdr=0, fd=None, ключ=None):
        df = читать_лист(путь, имя, hdr, fd)
        нет = проверить_колонки(тип, имя, df)
        if нет:
            пропало.append("«%s», лист «%s»: нет колонок %s" % (os.path.basename(путь), имя, ", ".join(нет)))
        d[ключ or имя] = df
        лог("      лист «%s»: %d строк" % (имя, len(df)))
        return df

    лог("   Сквозная аналитика: %s" % os.path.basename(S))
    cat = лист("сквозная", S, "Каталог", 2, ключ="каталог")
    лист("сквозная", S, "Сток текущий", 0, ключ="сток_тек")
    лист("сквозная", S, "Сток 2026", 0, ключ="сток_год")
    s1 = лист("сквозная", S, "Продажи 2026", 0, ключ="_п1")
    s2 = лист("сквозная", S, "Продажи текущий", 0, ключ="_п2")
    лист("сквозная", S, "Матрица РТГ 2026", 0, ключ="нормы")
    # «Матрицы» читаем позиционно: шапка там занимает только три ячейки,
    # и обычный читатель терял блок менеджеров из колонок 5–9.
    d["матрицы"] = читать_лист_позиционно(S, "Матрицы")

    if пропало:
        raise ОшибкаДанных(
            "Структура исходных файлов изменилась - расчёт остановлен, чтобы не посчитать неверно." +
            chr(10) + chr(10) + chr(10).join("  - " + x for x in пропало) + chr(10) + chr(10) +
            "Проверьте, что выгрузка сделана тем же способом, что и раньше.")

    # продажи = архив года + текущий месяц
    s2 = s2.drop(columns=[c for c in ("Проверка",) if c in s2.columns])
    общие = [c for c in s1.columns if c in s2.columns]
    d["продажи"] = pd.concat([s1[общие], s2[общие]], ignore_index=True)
    d.pop("_п1"); d.pop("_п2")

    if "динамика" in пути:
        лог("   Динамика стоков: %s" % os.path.basename(пути["динамика"]))
        cd = читать_лист(пути["динамика"], "Каталог", 2)
        if {"НС-Код", "Цена за ед.изм"} <= set(cd.columns):
            cd = cd[cd["НС-Код"].notna()][["НС-Код", "Цена за ед.изм"]].copy()
            cd.columns = ["НС-Код", "Цена_дин"]
            cd["Цена_дин"] = pd.to_numeric(cd["Цена_дин"], errors="coerce")
            d["цены"] = cd.groupby("НС-Код", as_index=False)["Цена_дин"].max()
            лог("      цен подтянуто: %d" % int(d["цены"]["Цена_дин"].gt(0).sum()))
    else:
        лог("   ! Файла динамики стоков нет - цены за ед. изм. будут неполными")

    if "матрица" in пути:
        лог("   Рабочая матрица: %s" % os.path.basename(пути["матрица"]))
        rm = читать_лист(пути["матрица"], "Рабочая таблица", 9, 10)
        d["рабочая_матрица"] = rm[rm["НС-Код"].notna()] if "НС-Код" in rm.columns else rm
        лог("      SKU в матрице: %d" % len(d["рабочая_матрица"]))
    else:
        лог("   ! Рабочей матрицы нет - актуальные статусы «складское/заказное» не проверяются")

    # Ликвидация ведётся ОТДЕЛЬНЫМ файлом: из рабочей матрицы позиция к
    # этому моменту уже удалена, а решение о выводе живёт только здесь.
    if "ликвидация" in пути:
        лог("   Список ликвидации: %s" % os.path.basename(пути["ликвидация"]))
        лист = листы_файла(пути["ликвидация"])[0]
        lq = читать_лист(пути["ликвидация"], лист, 0)
        кол = {str(c).strip().lower(): c for c in lq.columns}
        к_код, к_кат = кол.get("код"), кол.get("категория")
        if к_код and к_кат:
            lq = lq[[к_код, к_кат]].copy()
            lq.columns = ["НС-Код", "Категория"]
            lq["НС-Код"] = lq["НС-Код"].astype(str).str.strip()
            # шапка в выгрузке продублирована — отсекаем всё, что не НС-код
            lq = lq[lq["НС-Код"].str.match(r"^НС-\d+$", na=False)]
            lq["Категория"] = lq["Категория"].astype(str).str.strip()
            d["ликвидация"] = lq.drop_duplicates("НС-Код")
            лог("      позиций в списке: %d" % len(d["ликвидация"]))
        else:
            лог("      ! нет колонок «Код»/«Категория» - файл пропущен")
    else:
        лог("   ! Списка ликвидации нет - статус «Ликвидация» выводится по засолу")

    for ключ, имя in (("юнит_позиции", "юнит_поз"), ("юнит_склады", "юнит_скл")):
        if ключ in пути:
            лог("   %s: %s" % (ключ, os.path.basename(пути[ключ])))
            d[имя] = pd.read_excel(пути[ключ], sheet_name="Данные")
            лог("      строк: %d" % len(d[имя]))
    return d


# ------------------------------------------------------------------ подготовка
def подготовить(d: dict, cfg: dict, лог) -> dict:
    # Офисы — из выгрузки, а не из кода: инструмент должен работать
    # на любом периметре, а не только на том, под который писался.
    определить_офисы(d, cfg, лог)
    cat = d["каталог"]
    cat = cat[cat["НС-Код"].notna()].copy()
    cat = в_число(cat, ["Цена за ед.изм", "Коэффициент ликвидности"])
    if "цены" in d:
        cat = cat.merge(d["цены"], on="НС-Код", how="left")
    else:
        cat["Цена_дин"] = np.nan

    # A4. Актуальные статусы "складское/заказное" ведутся в рабочей матрице
    # пополнения, а в сквозной аналитике это поле вычисляется формулой
    # и отстаёт. Берём матрицу как источник истины, сквозную - как запасной.
    rm = d.get("рабочая_матрица")
    if (cfg.get("источники", {}).get("статус_sku_из", "матрица") == "матрица"
            and rm is not None and "Стратегия матрицы SKU" in rm.columns):
        акт = (rm[["НС-Код", "Стратегия матрицы SKU"]].dropna()
               .drop_duplicates("НС-Код").set_index("НС-Код")["Стратегия матрицы SKU"])
        акт = акт[акт.astype(str).str.strip() != ""]
        было = cat["Стратегия SKU"].copy() if "Стратегия SKU" in cat.columns else pd.Series(index=cat.index, dtype=object)
        cat["Стратегия SKU НСИ_сквозная"] = было
        подмена = cat["НС-Код"].map(акт)
        cat["Стратегия SKU"] = подмена.fillna(было)
        cat["Источник статуса"] = np.where(подмена.notna(), "рабочая матрица", "сквозная аналитика")
        изм = int((подмена.notna() & (подмена != было)).sum())
        лог("   Статус SKU: из рабочей матрицы взято %d позиций, расходилось со сквозной %d"
            % (int(подмена.notna().sum()), изм))
        d["_статус_расхождений"] = изм
    # Явный статус позиции для отчётов. Источники в порядке приоритета:
    #   1. список ликвидации — решение о выводе уже принято, оно главнее;
    #   2. рабочая матрица — актуальные «Складское» / «Заказное»;
    #   3. засол «вышел из матрицы (ликвидация)» — косвенный признак;
    #   4. остальное — вне матрицы пополнения.
    # Порядок важен: в матрице позиция может ещё числиться складской, а в
    # списке ликвидации уже стоять на вывод. Матрица обновляется реже.
    в_матрице = cat["НС-Код"].isin(set(rm["НС-Код"])) if rm is not None else pd.Series(False, index=cat.index)
    засол = cat.get("Статус засола NEW", pd.Series("", index=cat.index)).astype(str)
    ликвид = засол.str.contains("ликвидац", case=False, na=False)
    cat["Статус позиции"] = np.where(
        в_матрице, cat.get("Стратегия SKU", "").astype(str),
        np.where(ликвид, "Ликвидация (вышел из матрицы)", "Вне матрицы пополнения"))
    cat["Источник статуса позиции"] = np.where(
        в_матрице, "рабочая матрица",
        np.where(ликвид, "выведено по засолу", "нет в матрице"))

    lq = d.get("ликвидация")
    if lq is not None and len(lq):
        карта = lq.set_index("НС-Код")["Категория"]
        знач = cat["НС-Код"].map(карта)
        ликв_файл = знач.astype(str).str.contains("ликвидац", case=False, na=False)
        # Файл может пополниться другими категориями. Их не применяем:
        # «складское/заказное» — епархия рабочей матрицы, а не этого файла.
        прочие = sorted({str(v).strip() for v in карта.dropna().unique()
                         if str(v).strip() and "ликвидац" not in str(v).lower()})
        if прочие:
            лог("      ! в списке ликвидации есть другие категории (%s) - не применяются,"
                " статус по ним берётся из рабочей матрицы" % ", ".join(прочие[:5]))
        было = cat["Статус позиции"].copy()
        cat.loc[ликв_файл, "Статус позиции"] = "Ликвидация"
        cat.loc[ликв_файл, "Источник статуса позиции"] = "список ликвидации"
        спор = было[ликв_файл & в_матрице]
        лог("   Ликвидация: %d из %d позиций списка нашлись в каталоге"
            % (int(ликв_файл.sum()), len(lq)))
        if len(спор):
            лог("      из них %d числились в рабочей матрице (%s) - приоритет у ликвидации"
                % (len(спор), ", ".join("%s %d" % (k, v) for k, v in
                                        спор.value_counts().items())))
        d["_ликв_всего"] = len(lq)
        d["_ликв_в_каталоге"] = int(ликв_файл.sum())
        d["_ликв_спор"] = int(len(спор))
        d["_ликв_коды"] = set(карта.index)
    d["каталог"] = cat


    st = d["сток_тек"]; st = st[st["НС-Код"].notna()].copy()
    st = в_число(st, ["Общее кол-во запасов", "Общая себ-ть запасов", "Резерв"])
    st["Дата поступления"] = из_серийной_даты(pd.to_numeric(st["Дата поступления"], errors="coerce"))
    d["сток_тек"] = st

    sy = d["сток_год"]; sy = sy[sy["НС-Код"].notna()].copy()
    sy = в_число(sy, ["Общее кол-во запасов", "Общая себ-ть запасов", "Резерв"])
    d["сток_год"] = sy

    sl = d["продажи"]; sl = sl[sl["НС-Код"].notna()].copy()
    sl = в_число(sl, ["Оборот", "Продажи кол", "Продажи себ", "Продажи профит"])
    sl["Дата продажи"] = из_серийной_даты(pd.to_numeric(sl["Дата продажи"], errors="coerce"))
    d["продажи"] = sl

    nm = d["нормы"]; nm = nm[nm["НС-Код"].notna()].copy()
    nm = в_число(nm, ["min, ед.изм.", "max, ед.изм."])
    d["нормы"] = nm

    # период: от начала года до последней продажи
    посл = sl["Дата продажи"].max()
    if pd.isna(посл):
        raise ОшибкаДанных("В продажах нет ни одной корректной даты - проверьте колонку «Дата продажи».")
    нач = pd.Timestamp(year=посл.year, month=1, day=1)
    d["_дата"] = посл
    d["_дней"] = int((посл - нач).days) + 1
    d["_годовой"] = 365.0 / d["_дней"]
    d["_месяцы"] = [m for m in МЕСЯЦЫ if НОМЕР_МЕСЯЦА[m] <= посл.month]
    лог("   Период: 01.01.%d – %s (%d дней), годовое приведение x%.3f"
        % (посл.year, посл.strftime("%d.%m.%Y"), d["_дней"], d["_годовой"]))
    return d


def периметр(d: dict, cfg: dict, корень: str, лог) -> set:
    """Какие позиции считаем своими.

    Ключ периметра — ЧЕТВЁРКА: группа планирования, товарное направление,
    группа 1, группа 2. Раньше сверка шла по тройке, без группы
    планирования, и одно и то же сочетание «направление + Г1 + Г2» под
    другой группой планирования молча попадало в расчёт: у одного
    менеджера так набежало 1 114 чужих позиций и 7 млн ₽ оборота.
    """
    cat = d["каталог"]
    путь = os.path.join(корень, "config", "scope.json")
    менеджер = cfg["периметр"].get("категорийный_менеджер")
    ключи, полный = None, True
    if менеджер:
        m = d.get("матрицы")
        recs = []
        if m is not None:
            arr = m.values
            for i in range(len(arr)):
                row = arr[i]
                if len(row) > 8 and str(row[8]).strip() == менеджер:
                    # 4 — группа планирования, 5 — направление, 6 и 7 — группы
                    recs.append((str(row[4]), str(row[5]), str(row[6]), str(row[7])))
        if recs:
            ключи = set(recs)
            лог("   Периметр из файла: менеджер «%s», %d строк" % (менеджер, len(recs)))
    if ключи is None and cfg["периметр"].get("использовать_scope_json", True) \
            and os.path.exists(путь):
        sc = json.load(open(путь, encoding="utf-8"))
        полный = all("gp" in s for s in sc)
        if полный:
            ключи = {(s["gp"], s["td"], s["g1"], s["g2"]) for s in sc}
        else:
            # Старый файл без группы планирования. Считаем по тройке, но
            # говорим об этом: в периметр могут попасть чужие позиции.
            ключи = {(s["td"], s["g1"], s["g2"]) for s in sc}
            лог("   ! В config/scope.json нет поля «gp» (группа планирования):"
                " сверка идёт по тройке, в периметр могут попасть чужие позиции")
        лог("   Периметр из config/scope.json: %d сочетаний" % len(ключи))
    if not ключи:
        raise ОшибкаДанных(
            "Не удалось определить периметр." + chr(10) +
            "Либо укажите «категорийный_менеджер» в config/settings.yaml так, как он записан "
            "в листе «Матрицы» файла сквозной аналитики, либо положите список в config/scope.json.")
    if полный:
        свои = [(str(g), str(t), str(a), str(b)) in ключи
                for g, t, a, b in zip(cat["Группа планирования"], cat["Товарное направление"],
                                      cat["Группа 1"], cat["Группа 2"])]
    else:
        свои = [(str(t), str(a), str(b)) in ключи
                for t, a, b in zip(cat["Товарное направление"], cat["Группа 1"],
                                   cat["Группа 2"])]
    cat["МОЁ"] = свои
    mine = set(cat.loc[cat["МОЁ"], "НС-Код"])
    лог("   SKU в периметре: %d из %d" % (len(mine), len(cat)))
    if not mine:
        raise ОшибкаДанных("Периметр пуст: ни один SKU каталога не попал под заданные группы. "
                           "Проверьте config/scope.json - возможно, изменились названия групп.")
    return mine


# ------------------------------------------------------------------ OOS
def считать_oos(d: dict, mine: set, cfg: dict, лог) -> tuple[pd.DataFrame, pd.DataFrame]:
    МЕС = d["_месяцы"]
    посл = d["_дата"]
    дней_в = {НОМЕР_МЕСЯЦА[m]: pd.Period("%d-%02d" % (посл.year, НОМЕР_МЕСЯЦА[m]), "M").days_in_month
              for m in МЕС}
    дней_в[посл.month] = посл.day

    st = d["сток_год"]
    st = st[st["НС-Код"].isin(mine)].copy()
    st["Офис"] = st["Склад"].map(офис)
    st = st[st["Офис"].isin(ОСНОВНЫЕ_ОФИСЫ)]
    сток = st.groupby(["НС-Код", "Офис", "Месяц"], as_index=False).agg(
        Сток_кол=("Общее кол-во запасов", "sum"), Сток_себ=("Общая себ-ть запасов", "sum"))

    n = d["нормы"]
    n = n[n["НС-Код"].isin(mine) & n["Офис"].isin(ОСНОВНЫЕ_ОФИСЫ)]
    n = n.groupby(["НС-Код", "Офис", "Месяц"], as_index=False).agg(
        min_зап=("min, ед.изм.", "max"), max_зап=("max, ед.изм.", "max"))
    n = n[n["min_зап"] > 0]

    sl = d["продажи"]
    sl = sl[sl["НС-Код"].isin(mine)]
    прод = sl.groupby(["НС-Код", "Офис", "Месяц"], as_index=False).agg(
        Кол=("Продажи кол", "sum"), Об=("Оборот", "sum"))

    g = n.merge(сток, on=["НС-Код", "Офис", "Месяц"], how="left") \
         .merge(прод, on=["НС-Код", "Офис", "Месяц"], how="left")
    g[["Сток_кол", "Сток_себ", "Кол", "Об"]] = g[["Сток_кол", "Сток_себ", "Кол", "Об"]].fillna(0)
    g = g[g["Месяц"].isin(МЕС)].copy()

    # A2. Нормы в матрице заданы на весь год, включая месяцы, когда позиции
    # ещё не было в ассортименте. Без отсечки это даёт "мнимый" дефицит,
    # смещённый в начало года: он завышает OOS и рисует улучшение,
    # которого не было - на деле это просто расширение ассортимента.
    if cfg["дефицит"].get("учитывать_с_появления_sku", True):
        было = len(g)
        пс = сток[сток["Сток_кол"] > 0].copy(); пс["_м"] = пс["Месяц"].map(НОМЕР_МЕСЯЦА)
        пп = прод[прод["Кол"] > 0].copy();      пп["_м"] = пп["Месяц"].map(НОМЕР_МЕСЯЦА)
        появление = pd.concat([пс.groupby("НС-Код")["_м"].min(),
                               пп.groupby("НС-Код")["_м"].min()], axis=1).min(axis=1).rename("_появ")
        g = g.merge(появление, left_on="НС-Код", right_index=True, how="left")
        g["_м"] = g["Месяц"].map(НОМЕР_МЕСЯЦА)
        g = g[g["_появ"].notna() & (g["_м"] >= g["_появ"])].drop(columns=["_м", "_появ"]).copy()
        убрано = было - len(g)
        лог("   Отсечено мнимого дефицита (SKU ещё не было в ассортименте): %d связок (%.1f%%)"
            % (убрано, 100 * убрано / max(было, 1)))

    g["дней"] = g["Месяц"].map(lambda m: дней_в[НОМЕР_МЕСЯЦА[m]])
    g["OOS"] = (g["Сток_кол"] <= 0).astype(int)

    база = g[g.OOS == 0].groupby(["НС-Код", "Офис"], as_index=False).agg(
        кол=("Кол", "sum"), дней=("дней", "sum"), об=("Об", "sum"))
    база["спрос_сут"] = база["кол"] / база["дней"].replace(0, np.nan)
    база["цена"] = база["об"] / база["кол"].replace(0, np.nan)

    kf = float(cfg["дефицит"]["коэффициент_возврата_покупателя"])
    деф = g[g.OOS == 1].merge(база[["НС-Код", "Офис", "спрос_сут", "цена"]],
                              on=["НС-Код", "Офис"], how="left")
    деф["DNS"] = (деф["спрос_сут"] * деф["дней"]).fillna(0)
    деф["Lost_sales"] = деф["DNS"] * деф["цена"].fillna(0) * kf
    лог("   OOS: %d связок SKU×офис×месяц, из них в нуле %d (%.1f%%)"
        % (len(g), int(g.OOS.sum()), 100 * g.OOS.sum() / max(len(g), 1)))
    лог("   Упущенные продажи: %.2f млн руб. (коэф. %.2f)" % (деф.Lost_sales.sum() / 1e6, kf))
    return g, деф


# ------------------------------------------------------------------ факт
def построить_факт(d: dict, mine: set, oos: pd.DataFrame, деф: pd.DataFrame, cfg: dict, лог, окно_месяцев: int = 3) -> pd.DataFrame:
    МЕС = d["_месяцы"]
    sl = d["продажи"]; sl = sl[sl["НС-Код"].isin(mine)].copy()
    продажи = sl.groupby(["НС-Код", "Склад"], as_index=False).agg(
        Оборот=("Оборот", "sum"), Себест=("Продажи себ", "sum"), ВП=("Продажи профит", "sum"),
        Штук=("Продажи кол", "sum"), Строк=("Оборот", "size"),
        Клиентов=("Контрагенты список", "nunique"))

    # помесячная выручка по каждой связке - нужна для спарклайнов в отчётах
    мес_скл = sl.groupby(["НС-Код", "Склад", "Месяц"], as_index=False)["Оборот"].sum()
    мес_скл["_к"] = "М%02d" % 0
    мес_скл["_к"] = мес_скл["Месяц"].map(lambda m: "М%02d" % НОМЕР_МЕСЯЦА.get(m, 0))
    помесячно_ск = мес_скл.pivot_table(index=["НС-Код", "Склад"], columns="_к",
                                       values="Оборот", aggfunc="sum", fill_value=0).reset_index()

    # Полугодия. Второе почти всегда неполное — данные обрываются на
    # последней продаже, и это честно видно в подписи колонок.
    _пг = sl.copy()
    _пг["_пол"] = _пг["Месяц"].map(
        lambda m: 1 if НОМЕР_МЕСЯЦА.get(m, 0) <= 6 else 2)
    _св = _пг.groupby(["НС-Код", "Склад", "_пол"], as_index=False).agg(
        Оборот=("Оборот", "sum"), Себест=("Продажи себ", "sum"),
        ВП=("Продажи профит", "sum"), Штук=("Продажи кол", "sum"))
    полугодия = _св.pivot_table(index=["НС-Код", "Склад"], columns="_пол",
                                values=["Оборот", "Себест", "ВП", "Штук"],
                                aggfunc="sum", fill_value=0)
    полугодия.columns = ["%s_%dп" % (a, b) for a, b in полугодия.columns]
    полугодия = полугодия.reset_index()
    # Если все продажи попали в одно полугодие, колонки второго не будет
    # вовсе — дальше это ломает заполнение нулей. Создаём заранее.
    for _a in ("Оборот", "Себест", "ВП", "Штук"):
        for _b in (1, 2):
            _к = "%s_%dп" % (_a, _b)
            if _к not in полугодия.columns:
                полугодия[_к] = 0.0

    мес = sl.groupby(["НС-Код", "Месяц"], as_index=False)["Оборот"].sum()
    piv = мес.pivot_table(index="НС-Код", columns="Месяц", values="Оборот", fill_value=0)
    for c in МЕС:
        if c not in piv.columns: piv[c] = 0.0
    piv = piv[МЕС]
    cv = (piv.std(axis=1) / piv.mean(axis=1).replace(0, np.nan)).rename("CV")

    st = d["сток_тек"]; st = st[st["НС-Код"].isin(mine)]
    # Возраст запаса считаем ПО ДЕНЬГАМ. У позиции обычно несколько партий
    # разного возраста; если брать самую новую, одна коробка, приехавшая вчера,
    # "омолаживает" весь запас и выводит его из-под уценки.
    st = st.copy()
    st["_возр"] = (d["_дата"] - st["Дата поступления"]).dt.days
    st["_возр_себ"] = st["_возр"].fillna(0) * st["Общая себ-ть запасов"]
    рез_кол = "Резерв, ед.изм." if "Резерв, ед.изм." in st.columns else None
    агг = dict(Запас=("Общая себ-ть запасов", "sum"), Запас_ед=("Общее кол-во запасов", "sum"),
               Резерв=("Резерв", "sum"), Партия=("Дата поступления", "min"),
               Возраст_вес=("_возр_себ", "sum"), Возраст_старейшей=("_возр", "max"),
               Партий=("Дата поступления", "nunique"))
    if рез_кол: агг["Резерв_ед"] = (рез_кол, "sum")
    текущий = st.groupby(["НС-Код", "Склад"], as_index=False).agg(**агг)
    if "Резерв_ед" not in текущий.columns: текущий["Резерв_ед"] = 0.0
    текущий["Возраст"] = (текущий["Возраст_вес"]
                          / текущий["Запас"].replace(0, np.nan))
    текущий["Возраст_новейшей"] = (d["_дата"] - текущий["Партия"]).dt.days
    # A3. Резерв физически лежит на складе, но продать его нельзя.
    # Доступный запас - это то, чем реально можно торговать. Выключатель
    # в настройках был, но никогда не проверялся — теперь работает.
    if cfg.get("запас", {}).get("вычитать_резерв", True):
        доля = (текущий["Резерв_ед"] / текущий["Запас_ед"].replace(0, np.nan)).clip(0, 1)
        текущий["Запас_доступный"] = текущий["Запас"] * (1 - доля).fillna(1)
        текущий["Запас_ед_доступно"] = (текущий["Запас_ед"] - текущий["Резерв_ед"]).clip(lower=0)
    else:
        текущий["Запас_доступный"] = текущий["Запас"]
        текущий["Запас_ед_доступно"] = текущий["Запас_ед"]

    sy = d["сток_год"]; sy = sy[sy["НС-Код"].isin(mine)]
    помесячно = sy.groupby(["НС-Код", "Склад", "Месяц"], as_index=False)["Общая себ-ть запасов"].sum()
    средний = помесячно.groupby(["НС-Код", "Склад"], as_index=False)["Общая себ-ть запасов"].sum()
    средний["Общая себ-ть запасов"] /= max(len(МЕС), 1)      # средний за ВЕСЬ период
    средний.columns = ["НС-Код", "Склад", "Запас_средний"]

    посл_мес = МЕС[-1]
    z = sy[sy["Месяц"].eq(посл_мес)]
    if "Статус засола NEW" in z.columns:
        z = z[z["Статус засола NEW"].astype(str).str.startswith("ЗАСОЛ")]
        засол = z.groupby(["НС-Код", "Склад"], as_index=False)["Общая себ-ть запасов"].sum()
        засол.columns = ["НС-Код", "Склад", "Засол"]
    else:
        засол = pd.DataFrame(columns=["НС-Код", "Склад", "Засол"])

    f = продажи.merge(текущий, on=["НС-Код", "Склад"], how="outer") \
               .merge(средний, on=["НС-Код", "Склад"], how="outer") \
               .merge(засол,   on=["НС-Код", "Склад"], how="left")
    for c in ["Оборот","Себест","ВП","Штук","Строк","Клиентов","Запас","Запас_ед","Резерв",
              "Резерв_ед","Запас_доступный","Запас_ед_доступно","Запас_средний","Засол",
              "Возраст_вес","Возраст_старейшей","Партий"]:
        f[c] = pd.to_numeric(f[c], errors="coerce").fillna(0) if c in f.columns else 0.0
    # База для стоимости владения. Считается ЗДЕСЬ, на строке факта, и
    # дальше только суммируется — иначе подстановка «нет среднего, берём
    # текущий» срабатывает на одних уровнях и не срабатывает на других,
    # и владение перестаёт сходиться между уровнями дерева.
    f["Запас_база"] = f["Запас_средний"].where(f["Запас_средний"] > 0, f["Запас"])

    f["Офис"] = f["Склад"].map(офис)
    f["Тип склада"] = f["Склад"].map(тип_склада)
    f["Филиал"] = f["Склад"].map(филиал)

    H = ["Группа планирования","Товарное направление","Группа 1","Группа 2","Группа 3","Бренд"]
    cat = d["каталог"]
    доп = ["Название номенклатуры","Статус засола NEW","Стратегия SKU","Признак ликвидности",
           "Статус позиции", "Источник статуса позиции"]
    f = f.merge(cat[["НС-Код"] + [c for c in доп if c in cat.columns] + H], on="НС-Код", how="left")
    f = f.merge(cv, left_on="НС-Код", right_index=True, how="left")
    f = f.merge(помесячно_ск, on=["НС-Код", "Склад"], how="left")
    f = f.merge(полугодия, on=["НС-Код", "Склад"], how="left")
    # Заполняем ПОСЛЕ слияния: до него этих колонок в факте нет, а
    # присвоение нуля заранее превращало merge в пару «_x / _y», и в
    # свёртку попадала пустая колонка — весь разрез по полугодиям был нулевым.
    for _a in ("Оборот", "Себест", "ВП", "Штук"):
        for _b in (1, 2):
            _к = "%s_%dп" % (_a, _b)
            if _к in f.columns:
                f[_к] = pd.to_numeric(f[_к], errors="coerce").fillna(0)
            else:
                f[_к] = 0.0
    МК = [c for c in f.columns if len(str(c)) == 3 and str(c).startswith("М") and str(c)[1:].isdigit()]
    for c in МК:
        f[c] = pd.to_numeric(f[c], errors="coerce").fillna(0)

    # спрос за последние N месяцев — для расчёта перемещений между складами
    окно = МЕС[-int(окно_месяцев):] if окно_месяцев else МЕС
    спрос = sl[sl["Месяц"].isin(окно)].groupby(["НС-Код","Склад"], as_index=False)["Продажи кол"].sum()
    спрос.columns = ["НС-Код","Склад","Штук_окно"]
    f = f.merge(спрос, on=["НС-Код","Склад"], how="left")
    f["Штук_окно"] = f["Штук_окно"].fillna(0)

    oo = oos.groupby(["НС-Код","Офис"], as_index=False).agg(Связок=("OOS","size"), Дефицит=("OOS","sum"))
    ls = деф.groupby(["НС-Код","Офис"], as_index=False).agg(Упущено=("Lost_sales","sum"), DNS=("DNS","sum"))
    f = f.merge(oo, on=["НС-Код","Офис"], how="left").merge(ls, on=["НС-Код","Офис"], how="left")
    for c in ["Связок","Дефицит","Упущено","DNS"]:
        f[c] = f[c].fillna(0)
    # ВАЖНО: метрики OOS считаются на уровне ОФИСА, а строк в факте несколько
    # (по одной на склад офиса). Без этого при свёртке они умножатся на число складов.
    дубль = f.duplicated(subset=["НС-Код", "Офис"], keep="first")
    for c in ["Связок","Дефицит","Упущено","DNS"]:
        f.loc[дубль, c] = 0

    # КРИТИЧНО: пустые значения в ключах иерархии приводят к тому, что groupby
    # молча выбрасывает такие строки — и SKU без продаж пропадают из всех списков.
    for c in H + ["Название номенклатуры", "Статус засола NEW", "Стратегия SKU",
                  "Признак ликвидности", "Статус позиции", "Источник статуса позиции"]:
        if c in f.columns:
            f[c] = f[c].fillna("(не указано)").replace({"": "(не указано)", "None": "(не указано)"})
    лог("   Факт-таблица: %d строк, %d SKU, %d складов"
        % (len(f), f["НС-Код"].nunique(), f["Склад"].nunique()))
    return f


def разметить_сегменты(f: pd.DataFrame, cfg: dict) -> pd.DataFrame:
    гx, гy = cfg["сегментация"]["xyz_границы"]
    f["XYZ"] = pd.cut(f["CV"], [-0.01, гx, гy, 1e9],
                      labels=["X стабильный", "Y сезонный", "Z нерегулярный"])
    # SKU без продаж не имеют коэффициента вариации — им нужна своя категория,
    # иначе groupby их отбросит вместе со всем запасом, который на них висит
    f["XYZ"] = f["XYZ"].cat.add_categories(["- нет продаж"]).fillna("- нет продаж")
    sku = f.groupby("НС-Код", as_index=False)["Оборот"].sum().sort_values("Оборот", ascending=False)
    sku["куб"] = sku["Оборот"].cumsum() / max(sku["Оборот"].sum(), 1)
    a, b = cfg["сегментация"]["abc_границы"]
    sku["ABC"] = np.where(sku["куб"] <= a, "A", np.where(sku["куб"] <= b, "B", "C"))
    sku.loc[sku["Оборот"] <= 0, "ABC"] = "D (нет продаж)"
    return f.merge(sku[["НС-Код", "ABC"]], on="НС-Код", how="left")


# ------------------------------------------------------------------ свёртки
def сделать_свёртку(f: pd.DataFrame, keys: list[str], cfg: dict, годовой: float, дней: int) -> pd.DataFrame:
    ставка = float(cfg["экономика"]["ставка_хранения"]) + float(cfg["экономика"]["ставка_капитала"])
    порог_сущ = float(cfg["запас"]["порог_существенности_руб"])
    g = f.groupby(keys, as_index=False, observed=True, dropna=False).agg(
        SKU=("НС-Код","nunique"), Оборот=("Оборот","sum"), Себест=("Себест","sum"), ВП=("ВП","sum"),
        Запас=("Запас","sum"), Запас_средний=("Запас_средний","sum"), Запас_база=("Запас_база","sum"), Засол=("Засол","sum"),
        Запас_доступный=("Запас_доступный","sum"), Резерв_ед=("Резерв_ед","sum"),
        Запас_ед=("Запас_ед","sum"),
        Штук=("Штук","sum"), Строк=("Строк","sum"), Связок=("Связок","sum"),
        Дефицит=("Дефицит","sum"), Упущено=("Упущено","sum"),
        **{"%s_%dп" % (a, b): ("%s_%dп" % (a, b), "sum")
           for a in ("Оборот", "Себест", "ВП", "Штук") for b in (1, 2)
           if "%s_%dп" % (a, b) in f.columns})
    мк = [c for c in f.columns if len(str(c)) == 3 and str(c).startswith("М") and str(c)[1:].isdigit()]
    if мк:
        ряд = f.groupby(keys, as_index=False, observed=True, dropna=False)[мк].sum()
        g = g.merge(ряд, on=keys, how="left")
    акт = f[f["Оборот"] > 0].groupby(keys, observed=True, dropna=False)["НС-Код"].nunique().rename("SKU_активных")
    g = g.merge(акт, on=keys, how="left")
    g["SKU_активных"] = g["SKU_активных"].fillna(0).astype(int)
    g["SKU_мёртвых"] = g["SKU"] - g["SKU_активных"]

    # ВАЖНО: порог существенности гасит только ОТНОСИТЕЛЬНЫЕ метрики —
    # на копеечном запасе GMROI и рентабельность бессмысленны. Абсолютные
    # деньги (стоимость владения) он гасить не должен: содержание мелкого
    # запаса стоит ровно столько же за рубль, сколько содержание крупного,
    # и в сумме по периметру это заметные деньги.
    база_все = (g["Запас_база"] if "Запас_база" in g.columns
                else g["Запас_средний"].where(g["Запас_средний"] > 0, g["Запас"])).fillna(0)
    существенно = (база_все >= порог_сущ) | (g["Запас"] >= порог_сущ)
    g["Существенный"] = np.where(существенно, "да", "нет")
    база = база_все.replace(0, np.nan).where(существенно)

    порог = cfg["экономика"].get("порог_gmroi") or ставка
    # Маржа считается только от ПОЛОЖИТЕЛЬНОГО оборота. При обороте в
    # минусе (возвратов больше, чем продаж) деление отрицательного на
    # отрицательное давало плюс, и позиция с одними возвратами выглядела
    # прибыльной.
    _об = g["Оборот"].where(g["Оборот"] > 0)
    g["Маржа_%"]         = 100 * g["ВП"] / _об
    g["ВП_год"]          = g["ВП"] * годовой
    g["GMROI"]           = g["ВП_год"] / база
    g["Оборачиваемость"] = (g["Себест"] * годовой) / база
    g["Дней_запаса"]     = 365.0 / g["Оборачиваемость"].replace(0, np.nan)
    # на сколько хватит ТЕКУЩЕГО остатка при текущем темпе продаж
    # Дни запаса ограничены сверху: при продажах в несколько рублей за
    # период получаются сотни тысяч дней. Практического смысла в разнице
    # между «10 лет» и «1650 лет» нет, а лист от таких чисел нечитаем.
    _потолок = float(cfg.get("запас", {}).get("дней_запаса_потолок", 3650))
    g["Дней_запаса_тек"] = (g["Запас"] / (g["Себест"] / дней).replace(0, np.nan)
                            ).clip(upper=_потолок)
    g["Дней_запаса"] = g["Дней_запаса"].clip(upper=_потолок)
    # запас за вычетом резерва - то, чем реально можно торговать
    g["Запас_в_резерве"] = g["Запас"] - g["Запас_доступный"]
    g["Резерв_%"] = 100 * g["Запас_в_резерве"] / g["Запас"].replace(0, np.nan)
    g["Дней_запаса_доступно"] = (g["Запас_доступный"] / (g["Себест"] / дней).replace(0, np.nan)).clip(upper=_потолок)
    g["Владение"]        = база_все * ставка
    g["Эконом_прибыль"]  = g["ВП_год"] - g["Владение"]
    g["Рент_запаса_%"]   = 100 * g["Эконом_прибыль"] / база
    # Транзитный товар: запаса почти нет, он проезжает через склад.
    # GMROI = прибыль / вложенный запас; когда вложений нет, число уходит
    # в сотни и засоряет отчёт. Помечаем и не показываем метрику.
    транзит_дней = float(cfg["экономика"].get("транзит_до_дней", 15))
    # Транзит - это БЫСТРО ПРОДАЮЩИЙСЯ товар без остатка. У позиций вообще
    # без продаж дней запаса бесконечно много, а не мало: их сюда нельзя.
    транзит = ((g["Оборот"] > 0) & g["Дней_запаса"].notna()
               & np.isfinite(g["Дней_запаса"]) & (g["Дней_запаса"] < транзит_дней))
    g["Тип оборота"] = np.where(транзит, "транзитный", "складской")
    g.loc[транзит, ["GMROI", "Рент_запаса_%", "Оборачиваемость"]] = np.nan
    g["Отрабатывает"]    = np.where(g["GMROI"] >= порог, "да",
                            np.where(g["GMROI"].isna(), "-", "нет"))
    g["Засол_%"]         = 100 * g["Засол"] / g["Запас"].replace(0, np.nan)
    g["OOS_%"]           = 100 * g["Дефицит"] / g["Связок"].replace(0, np.nan)
    g["Доля_оборота_%"]  = 100 * g["Оборот"] / max(g["Оборот"].sum(), 1)
    g["Доля_запаса_%"]   = 100 * g["Запас"] / max(g["Запас"].sum(), 1)
    return g


