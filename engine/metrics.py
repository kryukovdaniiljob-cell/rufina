def все_свёртки(f: pd.DataFrame, cfg: dict, годовой: float, дней: int, лог) -> dict:
    out = {}
    for имя, keys in УРОВНИ.items():
        if not all(k in f.columns for k in keys):
            continue
        out[имя] = сделать_свёртку(f, keys, cfg, годовой, дней).sort_values("Оборот", ascending=False)
    out["L6_SKU"] = сделать_свёртку(
        f, ["НС-Код","Название номенклатуры","Бренд","Группа планирования","Товарное направление",
            "Группа 1","Группа 2","Группа 3","XYZ","ABC","Признак ликвидности","Статус позиции","Источник статуса позиции"],
        cfg, годовой, дней).sort_values("Оборот", ascending=False)
    лог("   Свёрток построено: %d" % len(out))
    return out


# ------------------------------------------------------------------ списки
def рабочие_списки(f: pd.DataFrame, св: dict, cfg: dict, годовой: float, лог) -> dict:
    ставка = float(cfg["экономика"]["ставка_хранения"]) + float(cfg["экономика"]["ставка_капитала"])
    медленный = float(cfg["запас"]["медленный_от_дней"])
    sku = св["L6_SKU"].copy()
    _чис = f.groupby("НС-Код")["Возраст_вес"].sum()
    _зн = f.groupby("НС-Код")["Запас"].sum()
    sku["Возраст"] = (_чис / _зн.replace(0, np.nan)).reindex(sku["НС-Код"]).values
    sku["Возраст_старейшей"] = f.groupby("НС-Код")["Возраст_старейшей"].max().reindex(sku["НС-Код"]).values
    sku["Партий"] = f.groupby("НС-Код")["Партий"].sum().reindex(sku["НС-Код"]).values
    sku["Клиентов"] = f.groupby("НС-Код")["Клиентов"].sum().reindex(sku["НС-Код"]).values
    sku["Запас_ед"] = f.groupby("НС-Код")["Запас_ед"].sum().reindex(sku["НС-Код"]).values
    статус = f.groupby("НС-Код")["Статус засола NEW"].first()
    sku["Статус засола NEW"] = статус.reindex(sku["НС-Код"]).values

    # A1. Товар, приехавший неделю назад, ещё не успел продаться - это
    # не кандидат на ликвидацию, а новинка без старта продаж. Смешивать
    # их нельзя: действия по ним прямо противоположные.
    новинка_до = float(cfg["запас"].get("новинка_до_дней", 90))
    без_продаж = sku[(sku["Запас"] > 0) & (sku["Оборот"] <= 0)]
    молодые = без_продаж["Возраст"].fillna(9999) < новинка_до
    новинки = без_продаж[молодые].sort_values("Запас", ascending=False)
    вывод = без_продаж[~молодые].sort_values("Запас", ascending=False)
    # Несколько партий при нулевых продажах = автозаказ продолжает докупать
    # то, что не продаётся. Это отдельная болезнь: остановить пополнение
    # важнее, чем уценить уже лежащее.
    порог_партий = int(cfg.get("план_задач", {}).get("повторные_закупки_от_партий", 3))
    for _сп in (вывод, новинки):
        if "Партий" in _сп.columns:
            _сп["Повторные_закупки"] = _сп["Партий"].fillna(0) >= порог_партий
    повт = вывод[вывод.get("Повторные_закупки", False) == True] if "Повторные_закупки" in вывод.columns else вывод.iloc[0:0]
    if len(повт):
        лог("   ! Докупаем непродающееся: %d позиций на %.2f млн руб. имеют %d+ партий и ноль продаж"
            % (len(повт), повт["Запас"].sum() / 1e6, порог_партий))
    # "Много дней запаса" и "товар залежался" - РАЗНЫЕ состояния, и лечатся
    # они по-разному. Крупная партия, приехавшая на прошлой неделе, даёт
    # огромный запас в днях, но уценивать там нечего: это вопрос к размеру
    # закупки. Разделяем по возрасту партии.
    пз = cfg.get("план_задач", {})
    возраст_уценки = float(пз.get("уценка_от_возраста_дней", 90))
    избыток = sku[(sku["Оборот"] > 0) & (sku["Дней_запаса_тек"] > медленный)
                  & (sku["Запас"] > 0) & (sku["Эконом_прибыль"] < 0)].copy()
    залежалось = избыток["Возраст"].fillna(9999) >= возраст_уценки
    медл = избыток[залежалось].sort_values("Эконом_прибыль")
    закупка = избыток[~залежалось].sort_values("Запас", ascending=False)

    # Продажи ниже себестоимости лечатся не уценкой, а ценой или условиями
    # закупки. Уценка тут только ускорит убыток: чем больше продадим, тем
    # больше потеряем.
    пк = cfg.get("проверки_качества", {})
    _доля = float(пк.get("символическая_цена_доля_оборота", 0.2))
    _мин = float(пк.get("символическая_цена_мин_себестоимость", 1000))
    убыт = sku[(sku["Оборот"] > 0) & (sku["ВП"] < 0)].copy()
    if len(убыт):
        # Документ на 13 ₽ при себестоимости 162 тыс. — это перемещение или
        # списание, а не продажа. Коммерческого решения он не требует.
        док = (убыт["Себест"] > _мин) & (убыт["Оборот"] < _доля * убыт["Себест"])
        цена = убыт[~док].sort_values("ВП")
        if int(док.sum()):
            лог("   Цена: отсечено %d документов по символической цене"
                " (оборот %.0f руб. при себестоимости %.0f руб.)"
                % (int(док.sum()), убыт[док]["Оборот"].sum(), убыт[док]["Себест"].sum()))
        лог("   ! Продаём ниже себестоимости: %d позиций, оборот %.2f млн руб.,"
            " убыток %.2f млн руб. за период"
            % (len(цена), цена["Оборот"].sum() / 1e6, -цена["ВП"].sum() / 1e6))
    else:
        цена = sku.iloc[0:0]

    # Статус позиции решает, какое действие вообще допустимо.
    # Дозаказ на склад имеет смысл только для СКЛАДСКИХ позиций:
    #   - в ликвидации закупка прямо противоречит принятому решению;
    #   - по заказным склад не держим вовсе, поэтому «дозаказать» — не то
    #     действие: сначала решение о вводе в матрицу пополнения.
    кр = cfg["кандидаты_на_развитие"]
    канд = sku[sku["ABC"].isin(кр["классы_abc"]) &
               (sku["OOS_%"] >= float(кр["минимальный_oos_процент"])) &
               (sku["Маржа_%"] >= float(кр["минимальная_маржа_процент"]))].sort_values("Оборот", ascending=False)
    if "Статус позиции" in канд.columns:
        _ст = канд["Статус позиции"].astype(str)
        _ликв = _ст.str.contains("ликвидац", case=False, na=False)
        if int(_ликв.sum()):
            лог("   Дозаказ: исключено %d позиций в ликвидации на %.2f млн руб. упущенных"
                % (int(_ликв.sum()), канд.loc[_ликв, "Упущено"].sum() / 1e6))
        канд = канд[~_ликв]
        складские = канд["Статус позиции"].astype(str).str.strip().str.lower().eq("складское")
        разв = канд[складские]
        в_матрицу = канд[~складские]
        if len(в_матрицу):
            лог("   Дозаказ: %d позиций не складские (заказное / вне матрицы) -"
                " им нужен ввод в матрицу, а не закупка" % len(в_матрицу))
    else:
        разв, в_матрицу = канд, канд.iloc[0:0]

    # перемещение: лежит без спроса на одном складе, дефицит на другом
    окно = int(cfg["дефицит"]["окно_спроса_месяцев"])
    по_офисам = f.groupby(["НС-Код", "Офис"], as_index=False).agg(
        Запас=("Запас","sum"), Запас_ед=("Запас_ед","sum"), Штук=("Штук_окно","sum"))
    деф = по_офисам[(по_офисам["Штук"] > 0) & (по_офисам["Запас_ед"] <= 0)][["НС-Код","Офис","Штук"]]
    деф.columns = ["НС-Код","Офис_деф","Спрос"]
    изб = по_офисам[(по_офисам["Запас_ед"] > 0) & (по_офисам["Штук"] <= 0)][["НС-Код","Офис","Запас_ед","Запас"]]
    изб.columns = ["НС-Код","Офис_изб","Кол","Сток"]
    mv = деф.merge(изб, on="НС-Код", how="inner")
    if len(mv):
        _пол = [c for c in ("Название номенклатуры", "Товарное направление", "Бренд", "Статус позиции") if c in f.columns]
        имена = f.groupby("НС-Код")[_пол].first()
        mv = mv.merge(имена, on="НС-Код", how="left")
        mv["Можно_переместить"] = np.minimum(mv["Спрос"], mv["Кол"])
        mv["Стоимость_перемещ"] = mv["Сток"] / mv["Кол"].replace(0, np.nan) * mv["Можно_переместить"]
        # Возить между городами то, что решено ликвидировать, — платить
        # логистику за товар, из которого мы выходим. Проще уценить на месте.
        if "Статус позиции" in mv.columns and not пз.get("перемещать_ликвидацию", False):
            _л = mv["Статус позиции"].astype(str).str.contains("ликвидац", case=False, na=False)
            if int(_л.sum()):
                лог("   Перемещение: исключено %d позиций в ликвидации на %.2f млн руб." % (int(_л.sum()), mv.loc[_л, "Стоимость_перемещ"].sum() / 1e6))
                mv = mv[~_л]
        mv = mv.sort_values("Стоимость_перемещ", ascending=False)
        # Один SKU не должен разъезжаться по нескольким маршрутам сразу:
        # берём самый крупный донор, остальное - следующей итерацией.
        было = len(mv)
        mv = mv.drop_duplicates("НС-Код", keep="first")
        # показатели позиции нужны и в строке перемещения: без маржи не
        # посчитать выгоду, без GMROI не видно, стоит ли товар усилий
        _п = [c for c in ("Маржа_%", "GMROI", "Владение", "Запас", "Запас_ед",
                          "Возраст", "Дней_запаса_тек") if c in sku.columns]
        mv = mv.merge(sku[["НС-Код"] + _п], on="НС-Код", how="left")
        mv["Где"] = mv["Офис_изб"].astype(str) + " -> " + mv["Офис_деф"].astype(str)
        mv["Сколько_ед"] = mv["Можно_переместить"]
        if было > len(mv):
            лог("   Перемещение: свёрнуто %d лишних маршрутов (один SKU - один маршрут)"
                % (было - len(mv)))
    # --- КОНКРЕТИКА ДЛЯ ПЛАНА РАБОТ -------------------------------------
    # Задача без ответа «где и сколько» не выполняется: менеджеру приходится
    # лезть в другие листы. Считаем это здесь, один раз, для всех списков.

    # 1. Где физически лежит запас. Раньше показывался только крупнейший
    #    склад и его доля — по такой строке нельзя понять, сколько именно
    #    штук и денег лежит в каждом месте, а действие делается по складам.
    _скл_кол = [c for c in ("Запас", "Запас_ед") if c in f.columns]
    поскл = (f[f["Запас"] > 0].groupby(["НС-Код", "Склад"], as_index=False)[_скл_кол].sum()
             .sort_values("Запас", ascending=False))
    _по_коду = {к: g for к, g in поскл.groupby("НС-Код")}

    def _кор(s):
        """Короткое имя склада: «Ижевск Воткинское шоссе РТГ Основной склад»
        в строке задачи не нужен целиком."""
        s = str(s)
        for мусор in (" РТГ Основной склад LV", " РТГ Основной склад", " РТГ", " склад"):
            s = s.replace(мусор, "")
        return s.strip()

    def _где_лежит(код):
        g = _по_коду.get(код)
        if g is None or not len(g):
            return ""
        части = []
        for _, r in g.head(3).iterrows():
            ед = r.get("Запас_ед")
            хв = (" %s ед." % _цел(ед)) if pd.notna(ед) and ед else ""
            части.append("%s:%s %s ₽" % (_кор(r["Склад"]), хв, _цел(r["Запас"])))
        если_ещё = len(g) - 3
        т = " · ".join(части)
        return т if если_ещё <= 0 else "%s · +%d скл." % (т, если_ещё)


    # 2. Где именно дефицит и сколько штук не хватило (DNS - спрос в дни нуля).
    деф_оф = f[f["Упущено"] > 0].groupby(["НС-Код", "Офис"], as_index=False).agg(
        Упущено=("Упущено", "sum"), DNS=("DNS", "sum"))
    деф_оф = деф_оф.sort_values("Упущено", ascending=False)
    _спис = деф_оф.groupby("НС-Код").apply(
        lambda g: " · ".join("%s: %s ед., упущено %s ₽"
                             % (_кор(r["Офис"]), _цел(r["DNS"]), _цел(r["Упущено"]))
                             for _, r in g.head(3).iterrows()),
        include_groups=False)
    _dns = деф_оф.groupby("НС-Код")["DNS"].sum()

    def _оснастить(df, вид):
        """Добавляет «где», «сколько» и отделяет резерв от свободного запаса."""
        if df is None or not len(df):
            return df
        df = df.copy()
        if вид == "дефицит":
            df["Где"] = df["НС-Код"].map(_спис).fillna("")
            df["Сколько_ед"] = df["НС-Код"].map(_dns).fillna(0)
            df["Резерв_руб"] = 0.0
            return df
        df["Где"] = df["НС-Код"].map(_где_лежит).fillna("")
        # Резерв физически лежит на складе, но он уже продан: уценивать
        # и выводить можно только свободный остаток.
        своб = df["Запас_доступный"] if "Запас_доступный" in df.columns else df["Запас"]
        df["Резерв_руб"] = (df["Запас"] - своб).clip(lower=0)
        df["Запас_свободный"] = своб
        df["Сколько_ед"] = (df["Запас_ед_доступно"] if "Запас_ед_доступно" in df.columns
                            else df.get("Запас_ед", 0))
        return df
        df = df.copy()
        if вид == "дефицит":
            df["Где"] = df["НС-Код"].map(_спис).fillna("")
            df["Сколько_ед"] = df["НС-Код"].map(_dns).fillna(0)
        else:
            df["Где"] = df["НС-Код"].map(_где_лежит).fillna("")
            df["Сколько_ед"] = df.get("Запас_ед", 0)
        return df

    # 3. Избыток над целевым покрытием: для «пересмотреть закупку» важен не
    #    весь запас, а только та часть, что сверх нормального покрытия.
    if len(закупка):
        доля_изб = (1 - медленный / закупка["Дней_запаса_тек"].replace(0, np.nan)).clip(0, 1).fillna(0)
        закупка = закупка.copy()
        закупка["Избыток_руб"] = закупка["Запас"] * доля_изб
        закупка["Избыток_ед"] = закупка.get("Запас_ед", 0) * доля_изб
        закупка["Избыток_доля"] = доля_изб

    # Везти туда, где спрашивают, и одновременно скидывать цену на месте —
    # взаимоисключающие решения. Перемещение выгоднее: продажа без скидки.
    if len(mv) and len(медл):
        _пересеч = медл["НС-Код"].isin(set(mv["НС-Код"]))
        if int(_пересеч.sum()):
            лог("   Уценка: снято %d позиций - по ним выгоднее перемещение"
                % int(_пересеч.sum()))
            медл = медл[~_пересеч]

    вывод, новинки = _оснастить(вывод, "запас"), _оснастить(новинки, "запас")
    медл, закупка = _оснастить(медл, "запас"), _оснастить(закупка, "запас")
    цена = _оснастить(цена, "запас")
    разв, в_матрицу = _оснастить(разв, "дефицит"), _оснастить(в_матрицу, "дефицит")

    лог("   Списки: вывести %d | новинки %d | залежалось %d | пересмотр закупки %d |" " дозаказать %d | ввод в матрицу %d | переместить %d SKU"
        % (len(вывод), len(новинки), len(медл), len(закупка), len(разв), len(в_матрицу), mv["НС-Код"].nunique() if len(mv) else 0))
    if len(новинки):
        лог("   (из «вывести» исключено %d позиций моложе %d дней на %.2f млн руб.)"
            % (len(новинки), int(новинка_до), новинки["Запас"].sum() / 1e6))
    return {"вывести": вывод, "новинки": новинки, "медленные": медл, "закупка": закупка,
            "развивать": разв, "в_матрицу": в_матрицу, "переместить": mv, "цена": цена, "sku": sku}
