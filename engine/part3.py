def план_факт(d: dict, mine: set, факт: pd.DataFrame, cfg: dict, лог) -> dict:
    """Сравнение факта с тремя видами плана по месяцам и по иерархии."""
    планы = [("ИТАН", "план_итан"), ("Оперативный", "план_опер"), ("Дефицит", "план_дефицит")]
    if not any(k in d for _, k in планы):
        лог("   ! Планов в выгрузке нет - раздел план-факта пропущен")
        return {}
    cat = d["каталог"]
    ключи = ["Товарное направление", "Группа 1", "Группа 2"]
    свои = set(map(tuple, cat.loc[cat["МОЁ"], ключи].astype(str).values.tolist()))
    МЕС = d["_месяцы"]
    посл = d["_дата"]
    полные = [m for m in МЕС if НОМЕР[m] < посл.month]      # текущий месяц неполный

    # факт по месяцам и по направлениям
    sl = d["продажи"]; sl = sl[sl["НС-Код"].isin(mine)]
    sl = sl.merge(cat[["НС-Код"] + ключи], on="НС-Код", how="left")
    факт_мес = sl.groupby("Месяц")["Оборот"].sum()
    факт_напр = sl.groupby("Товарное направление")["Оборот"].sum()

    итог = {"месяцы": МЕС, "полные": полные, "планы": {}, "по_направлениям": None}
    напр_таб = None
    for подпись, ключ in планы:
        pl = d.get(ключ)
        if pl is None or not len(pl):
            continue
        p = pl.copy()
        for m in МЕСЯЦЫ:
            if m in p.columns:
                p[m] = pd.to_numeric(p[m], errors="coerce").fillna(0)
        есть = [k for k in ключи if k in p.columns]
        if len(есть) == 3:
            p["_мой"] = [tuple(map(str, t)) in свои for t in p[есть].values]
            p = p[p["_мой"]]
        мес = {m: float(p[m].sum()) for m in МЕС if m in p.columns}
        план_полн = sum(мес.get(m, 0) for m in полные)
        факт_полн = float(факт_мес.reindex(полные).fillna(0).sum())
        итог["планы"][подпись] = {
            "по_месяцам": мес,
            "план_полные": план_полн, "факт_полные": факт_полн,
            "выполнение": 100 * факт_полн / план_полн if план_полн else None,
            "отрыв": факт_полн - план_полн,
            "план_всего_год": float(sum(p[m].sum() for m in МЕСЯЦЫ if m in p.columns)),
        }
        if подпись == "ИТАН" and "Товарное направление" in p.columns:
            н = p.groupby("Товарное направление")[полные].sum().sum(axis=1).rename("План")
            напр_таб = pd.concat([н, факт_напр.rename("Факт")], axis=1).fillna(0)
            напр_таб["Разница"] = напр_таб["Факт"] - напр_таб["План"]
            напр_таб["Выполнение_%"] = 100 * напр_таб["Факт"] / напр_таб["План"].replace(0, np.nan)
            напр_таб = напр_таб.sort_values("Разница").reset_index()
    итог["по_направлениям"] = напр_таб
    итог["факт_по_месяцам"] = {m: float(факт_мес.get(m, 0)) for m in МЕС}
    осн = итог["планы"].get("ИТАН") or next(iter(итог["планы"].values()), None)
    if осн and осн["выполнение"] is not None:
        лог("   План-факт (%d полных мес.): план %.2f млн, факт %.2f млн, выполнение %.1f%%"
            % (len(полные), осн["план_полные"] / 1e6, осн["факт_полные"] / 1e6, осн["выполнение"]))
    return итог


# ------------------------------------------------------------------ 2. LIKE-FOR-LIKE
def lfl(d: dict, mine: set, cfg: dict, лог) -> dict:
    """Сравнение с прошлым годом по тем же месяцам."""
    p25 = d.get("продажи25")
    if p25 is None or not len(p25):
        лог("   ! Продаж 2025 нет - Like-for-Like пропущен")
        return {}
    cat = d["каталог"]
    ключи = ["Товарное направление", "Группа 1", "Группа 2"]
    свои = set(map(tuple, cat.loc[cat["МОЁ"], ключи].astype(str).values.tolist()))
    МЕС = d["_месяцы"]
    полные = [m for m in МЕС if НОМЕР[m] < d["_дата"].month]

    p = p25.copy()
    for c in ("Оборот", "Продажи профит", "Продажи себ"):
        if c in p.columns:
            p[c] = pd.to_numeric(p[c], errors="coerce").fillna(0)
    есть = [k for k in ключи if k in p.columns]
    if len(есть) == 3:
        p["_мой"] = [tuple(map(str, t)) in свои for t in p[есть].values]
        p = p[p["_мой"]]
    if not len(p):
        лог("   ! В продажах 2025 нет позиций периметра - Like-for-Like пропущен")
        return {}

    sl = d["продажи"]; sl = sl[sl["НС-Код"].isin(mine)]
    sl = sl.merge(cat[["НС-Код"] + ключи], on="НС-Код", how="left")

    по_мес = []
    for m in МЕС:
        о25 = float(p[p["Месяц"] == m]["Оборот"].sum())
        о26 = float(sl[sl["Месяц"] == m]["Оборот"].sum())
        п25 = float(p[p["Месяц"] == m].get("Продажи профит", pd.Series(dtype=float)).sum())
        п26 = float(sl[sl["Месяц"] == m]["Продажи профит"].sum())
        по_мес.append({"месяц": m, "оборот25": о25, "оборот26": о26,
                       "рост_%": (100 * (о26 / о25 - 1)) if о25 else None,
                       "профит25_%": (100 * п25 / о25) if о25 else None,
                       "профит26_%": (100 * п26 / о26) if о26 else None})
    о25п = sum(x["оборот25"] for x in по_мес if x["месяц"] in полные)
    о26п = sum(x["оборот26"] for x in по_мес if x["месяц"] in полные)

    # Сравнение по направлениям валидно только если дерево категорий не менялось.
    # Между 2025 и 2026 товар переразнесли: то, что лежало в "ИСРМ / Внутренние
    # трубопроводные системы", стало отдельными направлениями Трубы и Фитинги.
    # Сравнивать такие направления год к году - сравнивать разные наборы товара.
    н25 = p.groupby("Товарное направление")["Оборот"].sum().rename("Оборот 2025")
    н26 = sl.groupby("Товарное направление")["Оборот"].sum().rename("Оборот 2026")
    напр = pd.concat([н25, н26], axis=1).fillna(0)
    напр["Доля 2025, %"] = 100 * напр["Оборот 2025"] / max(напр["Оборот 2025"].sum(), 1)
    напр["Доля 2026, %"] = 100 * напр["Оборот 2026"] / max(напр["Оборот 2026"].sum(), 1)
    напр["Сдвиг доли, п.п."] = напр["Доля 2026, %"] - напр["Доля 2025, %"]
    напр = напр.sort_values("Сдвиг доли, п.п.", key=abs, ascending=False).reset_index()
    напр = напр.rename(columns={напр.columns[0]: "Товарное направление"})
    сдвиг = float(напр["Сдвиг доли, п.п."].abs().max()) if len(напр) else 0.0
    сопоставимо = сдвиг < 15.0

    итог = {"по_месяцам": по_мес, "по_направлениям": напр, "полные": полные,
            "оборот25": о25п, "оборот26": о26п,
            "рост_%": (100 * (о26п / о25п - 1)) if о25п else None,
            "сопоставимо_по_направлениям": сопоставимо, "макс_сдвиг_доли": сдвиг}
    if not сопоставимо:
        лог("   ! Дерево категорий между годами менялось (сдвиг доли до %.0f п.п.)." % сдвиг)
        лог("     Сравнение по направлениям некорректно - показываем только итог по периметру")
    if итог["рост_%"] is not None:
        лог("   Like-for-Like: %.2f -> %.2f млн руб. (%+.1f%%) за %d полных месяцев"
            % (о25п / 1e6, о26п / 1e6, итог["рост_%"], len(полные)))
    return итог


