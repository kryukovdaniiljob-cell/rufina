def загрузить_дополнительно(пути: dict, d: dict, лог) -> dict:
    """Читает листы, которые до сих пор не использовались."""
    S = пути.get("сквозная")
    if not S:
        return d
    для_лога = []
    for имя, hdr, ключ in ДОП_ЛИСТЫ:
        try:
            df = читать_лист(S, имя, hdr)
            d[ключ] = df
            для_лога.append("%s=%d" % (ключ, len(df)))
        except Exception as e:
            лог("   ! лист «%s» прочитать не удалось: %s" % (имя, e))
    if для_лога:
        лог("   Дополнительные листы: " + ", ".join(для_лога))
    return d


