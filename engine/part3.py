ПОЛИТИКА = {
    ("A", "X"): "Держать всегда. Автозаказ, страховой запас минимальный - спрос предсказуем",
    ("A", "Y"): "Держать с сезонным запасом. Нормы пересматривать перед сезоном",
    ("A", "Z"): "Держать, но страховой запас выше. Спрос рваный - следить вручную",
    ("B", "X"): "Автозаказ по норме. Внимания почти не требует",
    ("B", "Y"): "Автозаказ с сезонной поправкой",
    ("B", "Z"): "Снизить норму, часть перевести в заказные",
    ("C", "X"): "Минимальная норма, автозаказ редкими партиями",
    ("C", "Y"): "Под заказ или минимальный запас в одном месте",
    ("C", "Z"): "Только под заказ. Складской запас не оправдан",
    ("D (нет продаж)", "X"): "Вывести",
    ("D (нет продаж)", "Y"): "Вывести",
    ("D (нет продаж)", "Z"): "Вывести",
}


def матрица_abc_xyz(sku: pd.DataFrame, cfg: dict, лог) -> pd.DataFrame | None:
    if "ABC" not in sku.columns or "XYZ" not in sku.columns:
        return None
    s = sku.copy()
    s["XYZ_к"] = s["XYZ"].astype(str).str[0]
    g = s.groupby(["ABC", "XYZ_к"], observed=True, dropna=False).agg(
        SKU=("НС-Код", "nunique"), Оборот=("Оборот", "sum"), Запас=("Запас", "sum"),
        ВП=("ВП", "sum"), Владение=("Владение", "sum"),
        Эконом_прибыль=("Эконом_прибыль", "sum")).reset_index()
    g["Доля_оборота_%"] = 100 * g["Оборот"] / max(g["Оборот"].sum(), 1)
    g["Доля_запаса_%"] = 100 * g["Запас"] / max(g["Запас"].sum(), 1)
    g["Политика"] = [ПОЛИТИКА.get((a, x), "") for a, x in zip(g["ABC"], g["XYZ_к"])]
    g = g.sort_values(["ABC", "XYZ_к"])
    лог("   Матрица ABC×XYZ: %d заполненных клеток" % len(g))
    return g


# ------------------------------------------------------------------ 4. ПОСТАВЩИКИ И КОДЫ ПРОБЛЕМ
def _из_матрицы(d: dict, колонки: list) -> pd.DataFrame | None:
    rm = d.get("рабочая_матрица")
    if rm is None:
        return None
    есть = [c for c in колонки if c in rm.columns]
    if "НС-Код" not in rm.columns or not есть:
        return None
    x = rm[["НС-Код"] + есть].copy()
    x = x.loc[:, ~pd.Index(x.columns).duplicated()]
    return x.drop_duplicates("НС-Код")


def поставщики(d: dict, sku: pd.DataFrame, cfg: dict, годовой: float, лог) -> pd.DataFrame | None:
    м = _из_матрицы(d, ["Поставщик", "Норма упаковки min", "Норма упаковки max"])
    if м is None or "Поставщик" not in м.columns:
        лог("   ! Поставщиков в рабочей матрице нет - разрез пропущен")
        return None
    ставка = float(cfg["экономика"]["ставка_хранения"]) + float(cfg["экономика"]["ставка_капитала"])
    порог = cfg["экономика"].get("порог_gmroi") or ставка
    s = sku.merge(м, on="НС-Код", how="inner")
    s["Поставщик"] = s["Поставщик"].fillna("(не указан)").replace("", "(не указан)")
    g = s.groupby("Поставщик", dropna=False).agg(
        SKU=("НС-Код", "nunique"), Оборот=("Оборот", "sum"), ВП=("ВП", "sum"),
        Запас=("Запас", "sum"), Запас_средний=("Запас_средний", "sum"),
        Владение=("Владение", "sum"),
        Эконом_прибыль=("Эконом_прибыль", "sum")).reset_index()
    мёртвые = s[s["Оборот"] <= 0].groupby("Поставщик")["НС-Код"].nunique().rename("SKU_без_продаж")
    g = g.merge(мёртвые, on="Поставщик", how="left")
    g["SKU_без_продаж"] = g["SKU_без_продаж"].fillna(0).astype(int)
    g["Маржа_%"] = 100 * g["ВП"] / g["Оборот"].replace(0, np.nan)
    # GMROI и стоимость владения должны делиться на ОДНО И ТО ЖЕ: на средний
    # запас за период. Текущий остаток для этого не годится — деньги лежали
    # весь год, а не только сегодня. Иначе в одной строке получается
    # «владение 19 909 руб. при запасе 14 460», и цифры не сходятся.
    база = g["Запас_средний"].where(g["Запас_средний"] > 0, g["Запас"]).replace(0, np.nan)
    g["ВП_год"] = g["ВП"] * годовой
    g["GMROI"] = g["ВП_год"] / база
    g["Отрабатывает"] = np.where(g["GMROI"] >= порог, "да", "нет")
    g = g.sort_values("Запас_средний", ascending=False)
    # Порядок колонок: текущий остаток и средний запас рядом — видно, что
    # владение считается от среднего, а не от того, что лежит сегодня.
    ПОР = ["Поставщик", "SKU", "SKU_без_продаж", "Оборот", "ВП", "ВП_год", "Маржа_%",
           "Запас", "Запас_средний", "Владение", "GMROI", "Эконом_прибыль",
           "Отрабатывает"]
    g = g[[c for c in ПОР if c in g.columns]]
    плохие = g[(g["Запас"] > 200000) & (g["GMROI"] < порог)]
    лог("   Поставщики: %d, из них не отрабатывают владение %d (запас %.2f млн руб.)"
        % (len(g), len(плохие), плохие["Запас"].sum() / 1e6))
    return g


