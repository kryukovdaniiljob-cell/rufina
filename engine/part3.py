def коды_проблем(d: dict, sku: pd.DataFrame, лог) -> pd.DataFrame | None:
    м = _из_матрицы(d, ["Код проблемы", "Поставщик", "Норма упаковки min", "Норма упаковки max"])
    if м is None or "Код проблемы" not in м.columns:
        лог("   ! Кодов проблем в рабочей матрице нет - раздел пропущен")
        return None
    s = sku.merge(м, on="НС-Код", how="inner")
    s["Код проблемы"] = s["Код проблемы"].astype(str)
    строки = []
    for код, текст in ОПИСАНИЕ_КОДОВ.items():
        под = s[s["Код проблемы"].str.contains(код, na=False)]
        if not len(под):
            continue
        строки.append({"Код": код, "Проблема": текст, "SKU": int(под["НС-Код"].nunique()),
                       "Запас": float(под["Запас"].sum()),
                       "Оборот": float(под["Оборот"].sum()),
                       "Содержание_год": float(под["Владение"].sum())})
    if not строки:
        return None
    t = pd.DataFrame(строки)
    лог("   Коды проблем: %s" % ", ".join("%s=%d SKU" % (r["Код"], r["SKU"]) for _, r in t.iterrows()))
    return t


# ------------------------------------------------------------------ 5. ПРИЧИНЫ ДЕФИЦИТА
def причины_дефицита(d: dict, деф: pd.DataFrame, sku: pd.DataFrame, лог) -> pd.DataFrame | None:
    if деф is None or not len(деф):
        return None
    зак = d.get("закупки")
    закупали = set()
    if зак is not None and "НС-Код" in зак.columns:
        z = зак.copy()
        мк = [m for m in МЕСЯЦЫ if m in z.columns]
        for m in мк:
            z[m] = pd.to_numeric(z[m], errors="coerce").fillna(0)
        закупали = set(z.loc[z[мк].sum(axis=1) > 0, "НС-Код"])
    прод = set(sku.loc[sku["Оборот"] > 0, "НС-Код"])

    x = деф.groupby("НС-Код", as_index=False).agg(
        Месяцев_в_нуле=("OOS", "sum"), Упущено=("Lost_sales", "sum"), DNS=("DNS", "sum"))

    def причина(k):
        if k not in закупали:
            return "Не закупали в этом году"
        if k in прод:
            return "Закупали, но не хватило"
        return "Закупали, но не продавалось"

    x["Причина"] = [причина(k) for k in x["НС-Код"]]
    g = x.groupby("Причина", as_index=False).agg(
        SKU=("НС-Код", "nunique"), Месяцев=("Месяцев_в_нуле", "sum"),
        Упущено=("Упущено", "sum"), DNS=("DNS", "sum")).sort_values("Упущено", ascending=False)
    g["Доля_упущенного_%"] = 100 * g["Упущено"] / max(g["Упущено"].sum(), 1)
    лог("   Причины дефицита: " + " | ".join("%s - %.2f млн" % (r["Причина"], r["Упущено"] / 1e6)
                                             for _, r in g.iterrows()))
    return g


# ------------------------------------------------------------------ 6. БЕНЧМАРК СКЛАДОВ
def бенчмарк_складов(св: dict, cfg: dict, дней: int, лог) -> dict | None:
    w = св.get("W1b_Офис")
    if w is None or not len(w):
        return None
    x = w[w["Запас"] > 1e6].copy()
    if len(x) < 2:
        return None
    лучший = x.loc[x["GMROI"].idxmax()]
    медиана = float(x["GMROI"].median())
    # Потолок: все дотянулись до лучшего. Это теоретический максимум, а не план -
    # у офисов разный ассортимент и разная клиентская база.
    x["Потолок_ВП"] = (лучший["GMROI"] * x["Запас_средний"] - x["ВП_год"]).clip(lower=0)
    # Реалистичная цель: отстающие подтягиваются до медианы по дивизиону.
    x["Цель_ВП"] = (медиана * x["Запас_средний"] - x["ВП_год"]).clip(lower=0)
    # Себестоимость продаж — за ПЕРИОД, а не за год. Делить её на 365
    # значит занизить суточный расход и раздуть «излишек».
    _сут = x["Себест"] / max(int(дней), 1)
    x["Излишек_запаса"] = (x["Запас"] - _сут * лучший["Дней_запаса"]).clip(lower=0)
    итог = {"эталон": str(лучший["Офис"]), "gmroi_эталона": float(лучший["GMROI"]),
            "медиана_gmroi": медиана, "дней_эталона": float(лучший["Дней_запаса"]),
            "потолок_вп": float(x["Потолок_ВП"].sum()),
            "цель_вп": float(x["Цель_ВП"].sum()),
            "излишек": float(x["Излишек_запаса"].sum()),
            "таблица": x[["Офис", "Запас", "Дней_запаса", "GMROI", "Цель_ВП", "Потолок_ВП",
                          "Излишек_запаса"]].sort_values("Цель_ВП", ascending=False)}
    лог("   Бенчмарк: эталон «%s» GMROI %.2f, медиана %.2f. Реалистичная цель +%.2f млн ВП/год "
        "(теоретический потолок +%.2f млн), излишек запаса %.2f млн"
        % (итог["эталон"], итог["gmroi_эталона"], медиана, итог["цель_вп"] / 1e6,
           итог["потолок_вп"] / 1e6, итог["излишек"] / 1e6))
    return итог


# ------------------------------------------------------------------ 7. ПРОГНОЗ ЗАПАСА
def прогноз_запаса(ряды: dict, S: dict, лог, вперёд: int = 6) -> dict | None:
    з = [v for v in (ряды.get("запас") or []) if v]
    if len(з) < 4:
        return None
    y = np.array(з, dtype=float)
    x = np.arange(len(y), dtype=float)
    k, b = np.polyfit(x, y, 1)
    буд = [float(k * (len(y) - 1 + i) + b) for i in range(1, вперёд + 1)]
    мес = ряды.get("месяцы") or []
    посл_i = len(мес) - 1
    имена = [МЕСЯЦЫ[(НОМЕР.get(мес[посл_i], 1) - 1 + i) % 12] for i in range(1, вперёд + 1)] if мес else []
    итог = {"наклон_млн_в_месяц": float(k), "прогноз": буд, "месяцы": имена,
            "текущий": float(y[-1]), "через_полгода": буд[-1] if буд else None,
            "рост_%": (100 * (буд[-1] / y[-1] - 1)) if буд and y[-1] else None}
    лог("   Прогноз запаса: %+.2f млн руб. в месяц, через %d мес. %.1f млн (сейчас %.1f)"
        % (k, вперёд, буд[-1] if буд else 0, y[-1]))
    return итог
