def собрать_задачи(списки: dict, cfg: dict, дата, годовой: float, лог) -> pd.DataFrame:
    """Плоский план работ: одна строка - одно действие по одной позиции.

    Задача попадает в план, только если она нужна, выполнима и окупает усилие.
    Мелочь ниже порога не выбрасывается, а сворачивается в одну строку.
    Порядок - по ГОДОВОЙ ВЫГОДЕ с поправкой на скорость отдачи.
    """
    пл = cfg.get("планирование", {})
    пз = cfg.get("план_задач", {})
    эк = cfg.get("экономика", {})
    ставка = float(эк.get("ставка_хранения", 0)) + float(эк.get("ставка_капитала", 0))
    ЮЭ = {}
    sku = списки.get("sku")
    if sku is not None and "ЮЭ_решение" in sku.columns:
        ЮЭ = dict(zip(sku["НС-Код"], sku["ЮЭ_решение"]))

    строки, мелочь = [], []
    for ключ, действие, порог_к, срок_к, влад_к, скорость, база in ДЕЙСТВИЯ:
        df = списки.get(ключ)
        if df is None or not len(df):
            continue
        порог = float(пз.get(порог_к, 0))
        срок = int(пл.get(срок_к, 14))          # SLA действия в днях
        владелец = пл.get(влад_к, "")
        поле = "Сумма действия, ₽" if база == "сумма" else "Эффект за год, ₽"
        for _, r in df.iterrows():
            s = _строка_задачи(r, действие, скорость, срок, владелец, ставка, годовой)
            if not s["Решение юнит-экономики"]:
                s["Решение юнит-экономики"] = ЮЭ.get(s["НС-Код"], "") or ""
            (строки if s[поле] >= порог else мелочь).append(s)

    if not строки and not мелочь:
        return pd.DataFrame()

    отсечено = pd.DataFrame()
    if строки:
        t = pd.DataFrame(строки)
        # Приоритет по ГОДОВОЙ ВЫГОДЕ с поправкой на скорость отдачи: действие,
        # которое не требует согласований, при равных деньгах идёт раньше.
        t["_вес"] = t["Эффект за год, ₽"] * t["_скорость"]
        t = t.sort_values("_вес", ascending=False).reset_index(drop=True)
        # СНАЧАЛА обрезаем до плана, ПОТОМ расставляем приоритеты. Если
        # считать квантили по всем кандидатам, а показывать только верхушку,
        # в плане окажутся сплошные единицы и двойки — половина плана
        # «сделать первым» это не приоритет, а список.
        максимум = int(пз.get("максимум_задач", 300))
        if len(t) > максимум:
            отсечено = t.iloc[максимум:].copy()
            t = t.iloc[:максимум].copy()
        q = t["_вес"].quantile([0.90, 0.70, 0.40]).tolist()
        t["Приоритет"] = np.where(t["_вес"] >= q[0], 1,
                          np.where(t["_вес"] >= q[1], 2,
                          np.where(t["_вес"] >= q[2], 3, 4)))
    else:
        t = pd.DataFrame()

    свёрнутые = []
    if пз.get("группировать_мелочь", True) and мелочь:
        м = pd.DataFrame(мелочь)
        for действие, g in м.groupby("Действие"):
            свёрнутые.append(_свёртка(g, действие, " - мелочь пакетом",
                                      "поштучно дешевле порога, оформить одним решением"))
    if len(отсечено):
        for действие, g in отсечено.groupby("Действие"):
            свёрнутые.append(_свёртка(g, действие, " - остальное",
                                      "за пределами плана, полный список в детальных листах"))

    if свёрнутые:
        t = pd.concat([t, pd.DataFrame(свёрнутые)], ignore_index=True)

    # Срок = SLA действия + неделя за каждый шаг приоритета. Раньше все
    # задачи одного действия получали одну дату: 199 уценок «до 25.09» —
    # это не план, а список пожеланий.
    шаг = int(пз.get("шаг_приоритета_дней", 7))
    сдвиг = (t["Приоритет"].fillna(5).astype(int) - 1).clip(lower=0) * шаг
    t["Срок"] = [(pd.Timestamp(дата) + pd.Timedelta(days=int(s) + int(d))).date().isoformat()
                 for s, d in zip(t["_sla"].fillna(14), сдвиг)]

    # Одна позиция в двух задачах — исполнитель должен об этом знать,
    # иначе он выполнит обе и посчитает эффект дважды.
    коды = t.loc[t["НС-Код"].astype(str).str.startswith("НС-"), "НС-Код"]
    повтор = set(коды[коды.duplicated(keep=False)])
    if повтор:
        по_коду = (t[t["НС-Код"].isin(повтор)].groupby("НС-Код")["Действие"]
                   .apply(lambda s: sorted(set(s))).to_dict())
        нов = []
        for _, стр in t.iterrows():
            в = _текст(стр.get("Внимание"))
            друг = [д for д in по_коду.get(стр.get("НС-Код"), [])
                    if д != стр.get("Действие")]
            if друг:
                в = ("%s; по позиции есть ещё задача: %s" % (в, ", ".join(друг))).strip("; ")
            нов.append(в)
        t["Внимание"] = нов
        лог("   Внимание: %d позиций получили по две задачи" % len(повтор))

    t = t.drop(columns=[c for c in ("_вес", "_скорость", "_sla") if c in t.columns])
    t = t.rename(columns=ПЕРЕИМЕНОВАНИЯ)
    t = t[[c for c in КОЛ_ЗАДАЧ if c in t.columns]]

    лог("   Задачи: %d строк, эффект %.2f млн руб./год (мелочи отсечено %d, сверх лимита %d)"
        % (len(t), t["Эффект за год, ₽"].sum() / 1e6, len(мелочь), len(отсечено)))
    for д, g in t.groupby("Действие"):
        лог("      %-34s %4d | сумма %10.0f | эффект %9.0f руб./год"
            % (д, len(g), g["Сумма действия, ₽"].sum(), g["Эффект за год, ₽"].sum()))
    return t


