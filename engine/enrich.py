# как наши списки соотносятся с решениями юнит-экономики
НАШЕ_К_ИХ = {
    "вывести":     {"вывести", "распродать"},
    "распродать":  {"распродать", "вывести", "придержать"},
    "развивать":   {"развивать", "оставить"},
    "новинка":     {"придержать", "оставить", "развивать", "-"},
    "переместить": {"оставить", "развивать", "придержать", "-"},
}


def подключить_юнит_экономику(sku: pd.DataFrame, d: dict, cfg: dict, лог) -> pd.DataFrame:
    """Добавляет к SKU готовые поля из выгрузки юнит-экономики."""
    if not cfg.get("источники", {}).get("использовать_юнит_экономику", True):
        return sku
    ue = d.get("юнит_поз")
    if ue is None or "НС-код" not in ue.columns:
        лог("   ! Выгрузки юнит-экономики нет - раздел сверки решений будет пропущен")
        return sku
    есть = {k: v for k, v in ПОЛЯ_ЮЭ.items() if k in ue.columns}
    u = ue[["НС-код"] + list(есть)].rename(columns={"НС-код": "НС-Код", **есть})
    u = u.drop_duplicates("НС-Код")
    for c in u.columns:
        if c.startswith("ЮЭ_") and c not in ("ЮЭ_решение", "ЮЭ_диагноз", "ЮЭ_коридор"):
            u[c] = pd.to_numeric(u[c], errors="coerce")
    # В выгрузке юнит-экономики «не считается» помечено длинным тире.
    # Приводим к обычному дефису прямо на входе. Иначе оно, во-первых,
    # доезжает до Excel, а во-вторых — сверка решений сравнивает наш «-»
    # с их «—» и не видит пары там, где её надо увидеть.
    for c in ("ЮЭ_решение", "ЮЭ_диагноз", "ЮЭ_коридор"):
        if c in u.columns:
            u[c] = u[c].map(lambda v: v.replace("—", "-")
                            if isinstance(v, str) else v)
    out = sku.merge(u, on="НС-Код", how="left")
    n = int(out["ЮЭ_решение"].notna().sum()) if "ЮЭ_решение" in out.columns else 0
    лог("   Юнит-экономика: подтянута к %d SKU из %d (%d полей)" % (n, len(out), len(есть)))
    return out


def наше_действие(списки: dict) -> pd.Series:
    """Какое действие предлагает наш расчёт по каждому SKU."""
    метки = {}
    for ключ, имя in (("вывести", "вывести"), ("новинки", "новинка"),
                      ("медленные", "распродать"), ("развивать", "развивать")):
        df = списки.get(ключ)
        if df is not None and len(df):
            for k in df["НС-Код"]:
                метки.setdefault(k, имя)
    mv = списки.get("переместить")
    if mv is not None and len(mv):
        for k in mv["НС-Код"].unique():
            метки.setdefault(k, "переместить")
    return pd.Series(метки, name="Наше_действие")


def сверка_решений(sku: pd.DataFrame, списки: dict, лог) -> dict:
    """Где наш расчёт расходится с уже принятыми решениями юнит-экономики."""
    if "ЮЭ_решение" not in sku.columns:
        return {}
    наше = наше_действие(списки)
    s = sku.merge(наше, left_on="НС-Код", right_index=True, how="left")
    s["Наше_действие"] = s["Наше_действие"].fillna("-")
    s = s[s["ЮЭ_решение"].notna()].copy()
    if not len(s):
        return {}

    def статус(r):
        их = str(r["ЮЭ_решение"]).strip()
        наш = str(r["Наше_действие"]).strip()
        if наш == "-" or их == "-":
            return "нет пары"
        return "согласны" if их in НАШЕ_К_ИХ.get(наш, set()) else "расходимся"

    s["Сверка"] = s.apply(статус, axis=1)
    расх = s[s["Сверка"] == "расходимся"].sort_values("Запас", ascending=False)
    итог = {
        "всего": len(s),
        "согласны": int((s["Сверка"] == "согласны").sum()),
        "расходимся": int((s["Сверка"] == "расходимся").sum()),
        "нет_пары": int((s["Сверка"] == "нет пары").sum()),
        "запас_расхождений": float(расх["Запас"].sum()),
        "таблица": s,
        "расхождения": расх,
    }
    for поле, ключ in (("ЮЭ_избыточный_сток", "избыточный_сток"),
                       ("ЮЭ_накоплен_долг", "накоплен_долг"),
                       ("ЮЭ_затраты_лежание", "затраты_лежание"),
                       ("ЮЭ_затраты_продажу", "затраты_продажу")):
        if поле in s.columns:
            итог[ключ] = float(pd.to_numeric(s[поле], errors="coerce").sum())
    лог("   Сверка с юнит-экономикой: согласны %d | расходимся %d | нет пары %d"
        % (итог["согласны"], итог["расходимся"], итог["нет_пары"]))
    if итог["расходимся"]:
        лог("      запас по расхождениям: %.2f млн руб." % (итог["запас_расхождений"] / 1e6))
    return итог


