def текст_уведомления(S: dict, cfg: dict) -> str:
    """Короткая сводка для мессенджера."""
    def м(x): return ("%.2f" % (x / 1e6)).replace(".", ",")
    def п(x): return ("%.1f" % x).replace(".", ",")
    def к(x): return ("%.2f" % x).replace(".", ",")
    строки = ["<b>Категорийная аналитика РТГ</b>",
              "Данные на %s" % S["дата"], ""]
    изм = S.get("изменения") or {}
    if изм.get("показатели"):
        важные = [x for x in изм["показатели"] if x["значимо"]][:4]
        if важные:
            строки.append("<b>Что изменилось с %s:</b>" % изм.get("с_датой", "прошлого раза"))
            for x in важные:
                стрелка = "🔺" if x["дельта"] > 0 else "🔻"
                оценка = "✅" if x["хорошо"] else "⚠️"
                ф = (м if x["тип"] == "руб" else п)
                строки.append("%s %s %s: %s → %s" % (оценка, стрелка, x["имя"], ф(x["было"]), ф(x["стало"])))
            строки.append("")
    строки += [
        "Запас: <b>%s млн ₽</b>" % м(S["запас"]),
        "GMROI: <b>%s</b> при пороге %s" % (к(S["gmroi"]), к(S["порог"])),
        "OOS: <b>%s %%</b>, упущено %s млн ₽" % (п(S["oos"]), м(S["упущено"])),
        "",
        "Можно высвободить: <b>%s млн ₽</b>" % м(S["высвобождение"]),
        "Экономия на хранении: %s млн ₽/год" % м(S["экономия"]),
    ]
    безд = S.get("бездействие") or {}
    if безд:
        строки.append("Цена бездействия за квартал: %s млн ₽" % м(безд["итого_потери"]))
    зд = S.get("задач_строк")
    if зд:
        строки += ["", "План работ: <b>%d задач</b>" % зд]
    return "\n".join(строки)


def уведомить(S: dict, cfg: dict, лог) -> bool:
    """Отправляет сводку в Telegram, если он настроен в config/settings.yaml."""
    у = cfg.get("уведомления") or {}
    токен, чат = у.get("telegram_токен"), у.get("telegram_chat_id")
    if not токен or not чат:
        лог("   Telegram не настроен (укажите токен и chat_id в config/settings.yaml) - пропускаю")
        return False
    import urllib.request, urllib.parse
    данные = urllib.parse.urlencode({
        "chat_id": str(чат), "text": текст_уведомления(S, cfg),
        "parse_mode": "HTML", "disable_web_page_preview": "true",
    }).encode()
    url = "https://api.telegram.org/bot%s/sendMessage" % токен
    try:
        with urllib.request.urlopen(urllib.request.Request(url, data=данные), timeout=20) as r:
            ok = json.loads(r.read().decode()).get("ok", False)
        лог("   Уведомление в Telegram: %s" % ("отправлено" if ok else "не принято"))
        return bool(ok)
    except Exception as e:
        лог("   ! Не удалось отправить в Telegram: %s" % e)
        return False
