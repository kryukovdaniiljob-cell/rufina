def безопасно(функция, путь, *а, **кв):
    """Если файл открыт в Excel, пишем рядом с пометкой, а не падаем."""
    try:
        return функция(путь, *а, **кв)
    except PermissionError:
        корень, расш = os.path.splitext(путь)
        новый = "%s (файл был открыт, %s)%s" % (корень, dt.datetime.now().strftime("%H-%M"), расш)
        лог("   ! «%s» открыт в Excel - сохраняю рядом:" % os.path.basename(путь))
        лог("     %s" % os.path.basename(новый))
        лог("     Закройте файл перед следующим расчётом, чтобы имя не менялось.")
        return функция(новый, *а, **кв)


def добрать_из_архива(пути: dict) -> dict:
    """Чего нет в 1_ВХОД — берём самое свежее из архива.

    Это нужно, чтобы выгрузки можно было обновлять ПО ОДНОЙ: положил новую
    сквозную — рабочая матрица, юнит-экономика и список ликвидации
    подтянутся с прошлого раза. Каждая такая подстановка печатается в
    журнале вместе с датой файла: молчаливой подмены быть не должно.

    Возвращает {тип: дата архива} по подставленным файлам — архивировать их
    повторно не нужно, они уже там.
    """
    из_архива = {}
    корень = os.path.join(КОРЕНЬ, "2_АРХИВ")
    if not os.path.isdir(корень):
        return из_архива
    папки = sorted((p for p in os.listdir(корень)
                    if os.path.isdir(os.path.join(корень, p))), reverse=True)[:5]
    for папка in папки:
        if len(пути) >= len(io_excel.SIGNATURES):
            break
        # В одной папке одного типа может лежать несколько файлов: выгрузку
        # перезалили под другим именем в тот же день. Берём самый свежий по
        # дате в имени — так же, как это делает сканирование 1_ВХОД. Раньше
        # побеждал первый по алфавиту, и подставиться могла прошлая выгрузка
        # при наличии свежей рядом.
        найдено = {}
        for имя in sorted(os.listdir(os.path.join(корень, папка))):
            if not имя.lower().endswith((".xlsb", ".xlsx", ".xlsm")) or имя.startswith("~$"):
                continue
            p = os.path.join(корень, папка, имя)
            код, _ = io_excel.опознать(p)
            if not код or код in пути:
                continue
            if код not in найдено or _новее(p, найдено[код]):
                найдено[код] = p
        for код, p in найдено.items():
            пути[код] = p
            из_архива[код] = папка
    return из_архива


def _новее(новый: str, старый: str) -> bool:
    """Какой из двух файлов свежее: по дате в имени, иначе по времени файла."""
    a, b = io_excel.дата_из_имени(новый), io_excel.дата_из_имени(старый)
    if a and b and a != b:
        return a > b
    return os.path.getmtime(новый) > os.path.getmtime(старый)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--вход", default=os.path.join(КОРЕНЬ, "1_ВХОД"))
    ap.add_argument("--без-архива", action="store_true")
    a = ap.parse_args()

    шапка("КАТЕГОРИЙНАЯ АНАЛИТИКА РТГ - запуск %s" % dt.datetime.now().strftime("%d.%m.%Y %H:%M"))
    cfg = yaml.safe_load(open(os.path.join(КОРЕНЬ, "config", "settings.yaml"), encoding="utf-8"))

    шапка("1. ПОИСК И РАСПОЗНАВАНИЕ ФАЙЛОВ")
    пути, замечания = io_excel.сканировать(a.вход)
    for z in замечания:
        лог("   ! " + z)
    # Недостающие типы добираем из архива, чтобы можно было класть в 1_ВХОД
    # только те файлы, которые изменились.
    из_архива = добрать_из_архива(пути)
    if not пути:
        raise ОшибкаДанных(
            "В папке «%s» не найдено ни одной распознанной выгрузки." % a.вход + chr(10) +
            "Положите туда файлы сквозной аналитики, динамики стоков, рабочей матрицы и юнит-экономики.")
    for к, p in пути.items():
        отк = " [из архива %s]" % из_архива[к] if к in из_архива else ""
        лог("   %-3s %-14s <- %s%s" % ("АРХ" if к in из_архива else "OK", к, os.path.basename(p), отк))
    нет = sorted(set(io_excel.SIGNATURES) - set(пути))
    if нет:
        лог("   -   не найдено вовсе: %s" % ", ".join(io_excel.SIGNATURES[k]["имя"] for k in нет))
    if "сквозная" not in пути:
        raise ОшибкаДанных(
            "Нет файла сквозной аналитики - без него расчёт невозможен." + chr(10) +
            "Положите его в папку «%s» и запустите снова." % a.вход)
    if "сквозная" in из_архива:
        лог("")
        лог("   " + "!" * 66)
        лог("   ВНИМАНИЕ: свежей сквозной аналитики в 1_ВХОД нет - взята из архива.")
        лог("   Отчёт будет ПОВТОРЯТЬ прошлый расчёт. Положите новую выгрузку в 1_ВХОД.")
        лог("   " + "!" * 66)

    шапка("2. ЧТЕНИЕ ДАННЫХ")
    d = metrics.загрузить(пути, лог)
    d = metrics.подготовить(d, cfg, лог)
    d = part3.загрузить_дополнительно(пути, d, лог)
    mine = metrics.периметр(d, cfg, КОРЕНЬ, лог)

    # Разрыв между датой в имени выгрузки и датой последних данных в ней -
    # самая частая причина недоверия к отчёту: файл называется 14.09,
    # а продаж в нём по 11.09. Говорим об этом прямо и сразу.
    дат_файла = io_excel.дата_из_имени(пути["сквозная"])
    дат_данных = d["_дата"].date()
    if дат_файла and дат_файла != дат_данных:
        разрыв = (дат_файла - дат_данных).days
        лог("")
        лог("   " + "!" * 66)
        лог("   ВНИМАНИЕ: выгрузка названа «%s», но последние данные в ней - %s."
            % (дат_файла.strftime("%d.%m.%y"), дат_данных.strftime("%d.%m.%Y")))
        if разрыв > 0:
            лог("   Разрыв %d дн. Это нормально: выгрузка сделана утром, а продажи"
                % разрыв)
            лог("   за последние дни ещё не попали в хранилище (выходные, задержка загрузки).")
        лог("   ОТЧЁТ БУДЕТ ЗА ПЕРИОД ПО %s - это дата данных, а не дата файла."
            % дат_данных.strftime("%d.%m.%Y"))
        лог("   " + "!" * 66)
        лог("")
    S_разрыв = {"дата_файла": дат_файла.strftime("%d.%m.%Y") if дат_файла else None,
                "дата_данных": дат_данных.strftime("%d.%m.%Y")}

    # C1. Предупредить, если загрузили не более свежие данные, чем в прошлый раз
    сн = os.path.join(КОРЕНЬ, "база", enrich.СНИМОК)
    if os.path.exists(сн):
        try:
            ист = json.load(open(сн, encoding="utf-8"))
            даты = [dt.datetime.strptime(x["дата_данных"], "%d.%m.%Y").date()
                    for x in ист if x.get("дата_данных")]
            if даты and d["_дата"].date() < max(даты):
                лог("   !! ВНИМАНИЕ: данные в файлах (%s) СТАРШЕ, чем в прошлом расчёте (%s)."
                    % (d["_дата"].strftime("%d.%m.%Y"), max(даты).strftime("%d.%m.%Y")))
                лог("      Похоже, загружена старая выгрузка. Проверьте файлы.")
            elif даты and d["_дата"].date() == max(даты):
                лог("   ! Данные той же даты, что и в прошлом расчёте (%s) - пересчёт."
                    % d["_дата"].strftime("%d.%m.%Y"))
        except Exception:
            pass

    шапка("3. РАСЧЁТ ДЕФИЦИТА (OOS)")
    oos, деф = metrics.считать_oos(d, mine, cfg, лог)

    шапка("4. ФАКТ-ТАБЛИЦА И СЕГМЕНТАЦИЯ")
    факт = metrics.построить_факт(d, mine, oos, деф, cfg, лог, int(cfg["дефицит"]["окно_спроса_месяцев"]))
    факт = metrics.разметить_сегменты(факт, cfg)

    шапка("5. СВЁРТКИ ПО ИЕРАРХИИ")
    св = metrics.все_свёртки(факт, cfg, d["_годовой"], d["_дней"], лог)

    шапка("6. РАБОЧИЕ СПИСКИ")
    списки = metrics.рабочие_списки(факт, св, cfg, d["_годовой"], лог)

    шапка("7. ЮНИТ-ЭКОНОМИКА И СВЕРКА РЕШЕНИЙ")
    списки["sku"] = enrich.подключить_юнит_экономику(списки["sku"], d, cfg, лог)
    сверка = enrich.сверка_решений(списки["sku"], списки, лог)

    шапка("8. ПРОВЕРКИ КАЧЕСТВА ДАННЫХ")
    кач = проверки_качества(d, mine, факт, cfg)
    for p in кач["проверки"]:
        лог("   - %-62s %s" % (p[0][:62], p[1]))

    период = {"дата": d["_дата"], "дней": d["_дней"]}
    S = reports.сводка(св, списки, oos, деф, cfg, период, лог)
    S.update({k: v for k, v in кач.items() if k in ("символические", "проверки")})
    S["даты"] = S_разрыв
    S["посчитано"] = dt.date.today().strftime("%d.%m.%Y")
    S["сверка"] = {k: v for k, v in сверка.items() if k not in ("таблица", "расхождения")}
    нов = списки.get("новинки")
    S["новинки"] = {"sku": len(нов) if нов is not None else 0,
                    "запас": float(нов["Запас"].sum()) if нов is not None and len(нов) else 0.0}

    шапка("9. СРАВНЕНИЕ С ПРЕДЫДУЩИМ РАСЧЁТОМ")
    S["изменения"] = enrich.сравнить_с_прошлым(S, списки, КОРЕНЬ, cfg, лог)

    шапка("10. ПЛАН-ФАКТ, LFL И ОСТАЛЬНЫЕ РАЗРЕЗЫ")
    ряды = ряды_по_месяцам(d, mine, oos)
    П = {}
    П["план_факт"]   = part3.план_факт(d, mine, факт, cfg, лог)
    П["lfl"]         = part3.lfl(d, mine, cfg, лог)
    П["abc_xyz"]     = part3.матрица_abc_xyz(списки["sku"], cfg, лог)
    П["поставщики"]  = part3.поставщики(d, списки["sku"], cfg, d["_годовой"], лог)
    П["коды"]        = part3.коды_проблем(d, списки["sku"], лог)
    П["причины"]     = part3.причины_дефицита(d, деф, списки["sku"], лог)
    П["бенчмарк"]    = part3.бенчмарк_складов(св, cfg, d["_дней"], лог)
    П["прогноз"]     = part3.прогноз_запаса(ряды, S, лог)
    списки["abc_xyz"]    = П["abc_xyz"]
    списки["поставщики"] = П["поставщики"]
    списки["портфель"]   = portfolio.решения(св, факт, cfg, d["_годовой"], лог)
    списки["бренды"]     = brands.бренды_по_группам(св, списки["sku"], cfg, d["_годовой"], лог)
    списки["коды"]       = П["коды"]
    списки["причины"]    = П["причины"]
    S["часть3"] = {k: v for k, v in П.items()
                   if k in ("план_факт", "lfl", "бенчмарк", "прогноз")}
    S["часть3"]["план_факт"] = {k: v for k, v in (П["план_факт"] or {}).items()
                                if k != "по_направлениям"}
    S["часть3"]["lfl"] = {k: v for k, v in (П["lfl"] or {}).items() if k != "по_направлениям"}
    if П["бенчмарк"]:
        S["часть3"]["бенчмарк"] = {k: v for k, v in П["бенчмарк"].items() if k != "таблица"}
    списки["план_напр"] = (П["план_факт"] or {}).get("по_направлениям")
    списки["lfl_напр"]  = (П["lfl"] or {}).get("по_направлениям")
    списки["бенчмарк"]  = (П["бенчмарк"] or {}).get("таблица")

    списки["факт"] = факт
    списки["задачи"] = enrich.собрать_задачи(списки, cfg, d["_дата"], d["_годовой"], лог)
    списки["сверка"] = сверка.get("таблица")
    списки["расхождения"] = сверка.get("расхождения")
    # Сходятся ли числа между уровнями и листами. Отдельные формулы видно
    # глазами, согласованность — нет: за неделю три ошибки нашлись именно
    # так, когда сумма по позициям не совпадала с итогом.
    списки["самопроверка"] = selfcheck.проверить(св, S, списки, cfg, лог)
    S["приоритеты"] = enrich.приоритеты(S, cfg)
    S["бездействие"] = enrich.цена_бездействия(S, cfg, кварталов=1.0)
    лог("   Цена бездействия за квартал: %.2f млн руб. потерь, %.2f млн заморожено"
        % (S["бездействие"]["итого_потери"] / 1e6, S["бездействие"]["замороженный_капитал"] / 1e6))

    дата = d["_дата"].date()
    папка = os.path.join(КОРЕНЬ, "3_ОТЧЁТЫ", dt.date.today().isoformat())
    os.makedirs(папка, exist_ok=True)
    шапка("11. НАКОПЛЕНИЕ ИСТОРИИ")
    копить_историю(d, mine, факт, cfg, дата)

    шапка("12. СБОРКА ОТЧЁТОВ")
    сделано = []
    # ряды уже посчитаны в шаге 10
    гр = charts.все(S, св, ряды, os.path.join(папка, "графики"), лог)
    сегодня = dt.date.today()
    # Имя отчёта должно отвечать на два вопроса сразу: когда посчитали и
    # по какую дату данные. Выгрузка от 14.09 может содержать продажи по 11.09 -
    # без этого в имени отчёт выглядит устаревшим, хотя он свежий.
    # Префикс в имени файла: у каждого менеджера своя папка, но отчёты
    # неизбежно окажутся рядом — в почте, в общей папке, во вложении.
    # Имена и даты у них одинаковые, различить нельзя.
    пре = str(cfg.get("отчёты", {}).get("префикс_имени", "") or "").strip()
    пре = ("(%s) " % пре) if пре else ""
    if дата == сегодня:
        суф = сегодня.isoformat()
    else:
        суф = "%s_данные_по_%s" % (сегодня.isoformat(), дата.strftime("%d.%m"))
    if cfg["отчёты"]["excel"]:
        сделано.append(безопасно(reports.excel, os.path.join(папка, "%sРасчёты_%s.xlsx" % (пре, суф)),
                                 св, списки, S, cfg, лог))
    if cfg["отчёты"]["word"]:
        сделано.append(безопасно(word, os.path.join(папка, "%sАналитическая_записка_%s.docx" % (пре, суф)),
                                 св, списки, S, cfg, лог, гр))
    if cfg["отчёты"]["дашборд"]:
        pass
        p = безопасно(dashboard, os.path.join(папка, "%sДашборд_%s.html" % (пре, суф)),
                      св, списки, S, cfg, ряды, лог)
        сделано.append(p)
        docs = os.path.join(КОРЕНЬ, "docs")
        os.makedirs(docs, exist_ok=True)
        shutil.copy(p, os.path.join(docs, "index.html"))
        лог("   Дашборд опубликован: docs/index.html")

    if not a.без_архива:
        шапка("13. АРХИВИРОВАНИЕ ИСХОДНИКОВ")
        арх = os.path.join(КОРЕНЬ, "2_АРХИВ", сегодня.isoformat())
        os.makedirs(арх, exist_ok=True)
        for к, p in пути.items():
            if к in из_архива:
                continue          # файл уже лежит в архиве, переносить нечего
            цель = os.path.join(арх, os.path.basename(p))
            try:
                if os.path.exists(цель):
                    os.remove(цель)      # повторный расчёт за день заменяет архив
                shutil.move(p, цель)
                лог("   -> 2_АРХИВ/%s/%s" % (сегодня.isoformat(), os.path.basename(p)))
            except Exception as e:
                лог("   ! не удалось переместить %s: %s" % (os.path.basename(p), e))

    шапка("ГОТОВО")
    лог("Дата данных : %s" % S["дата"])
    лог("Периметр    : %s SKU, запас %s млн ₽, оборот %s млн ₽"
        % (reports.цел(S["sku"]), reports.млн(S["запас"]), reports.млн(S["оборот"])))
    лог("GMROI       : %s при пороге %s" % (reports.пц(S["gmroi"], 2), reports.пц(S["порог"], 2)))
    лог("OOS         : %s %%, упущено %s млн ₽" % (reports.пц(S["oos"]), reports.млн(S["упущено"])))
    лог("Потенциал   : высвободить %s млн ₽, экономия %s млн ₽/год"
        % (reports.млн(S["высвобождение"]), reports.млн(S["экономия"])))
    лог("")
    for f in сделано:
        лог("  " + os.path.relpath(f, КОРЕНЬ))

    зд = списки.get("задачи")
    S["задач_строк"] = int(len(зд)) if зд is not None else 0
    enrich.уведомить(S, cfg, лог)
    enrich.сохранить_снимок(S, списки, КОРЕНЬ, cfg, лог)
    json.dump(S, open(os.path.join(папка, "сводка.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1, default=str)
    open(os.path.join(папка, "журнал.txt"), "w", encoding="utf-8").write(chr(10).join(ЖУРНАЛ))
    return папка


