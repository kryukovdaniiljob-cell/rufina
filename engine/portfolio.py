# -*- coding: utf-8 -*-
"""Решения по портфелю: бренды, направления, склады.

Лист «0.Задачи» работает на уровне позиции. Но убыточный бренд нельзя
починить, перебирая его SKU по одному: там нужно решение на уровне бренда —
цена, условия закупки или вывод целиком. То же со складом и направлением.

Этот модуль собирает такие решения в один список: объект, деньги, что
именно предлагается и почему.
"""
from __future__ import annotations
import numpy as np
import pandas as pd

ЭП = "Эконом_прибыль"

# уровень -> (ключ свёртки, полный набор ключей группировки, что показывать в «Объект»)
СЛОИ = [("Бренд", "B1_Бренд", ["Бренд"], "Бренд"),
        ("Направление", "L2_Направление",
         ["Группа планирования", "Товарное направление"], "Товарное направление"),
        ("Склад", "W3_Склад", ["Филиал", "Офис", "Склад", "Тип склада"], "Склад")]


def _ц(v) -> str:
    try:
        return format(int(round(float(v))), ",d").replace(",", chr(160))
    except (TypeError, ValueError):
        return "0"


def _убытки(f: pd.DataFrame, keys: list[str], cfg: dict) -> pd.DataFrame:
    """Сколько прибыли теряется на позициях, продаваемых ниже себестоимости.

    Считается ПО ПОЛНОМУ ключу уровня: одно и то же название направления
    встречается в разных группах планирования, и складывать их нельзя —
    иначе строка из одной позиции получит убыток всего направления.
    """
    пк = cfg.get("проверки_качества", {})
    доля = float(пк.get("символическая_цена_доля_оборота", 0.2))
    мин = float(пк.get("символическая_цена_мин_себестоимость", 1000))
    keys = [k for k in keys if k in f.columns]
    if not keys:
        return pd.DataFrame()
    g = f.groupby(keys + ["НС-Код"], as_index=False, observed=True, dropna=False).agg(
        Оборот=("Оборот", "sum"), Себест=("Себест", "sum"), ВП=("ВП", "sum"))
    м = g[(g["Оборот"] > 0) & (g["ВП"] < 0)].copy()
    if not len(м):
        return pd.DataFrame()
    # документ на 13 ₽ при себестоимости 162 тыс. — это перемещение или
    # списание, а не продажа; коммерческого решения он не требует
    док = (м["Себест"] > мин) & (м["Оборот"] < доля * м["Себест"])
    м = м[~док]
    if not len(м):
        return pd.DataFrame()
    out = м.groupby(keys, as_index=False, observed=True, dropna=False).agg(
        Убыток_цена=("ВП", "sum"), Позиций_в_минус=("НС-Код", "nunique"))
    out["Убыток_цена"] = (-out["Убыток_цена"]).clip(lower=0)
    return out


def _рек(r, порог: float) -> tuple[str, str, str]:
    """Возвращает (решение, обоснование, срочность)."""
    оборот = float(r.get("Оборот") or 0)
    вп = float(r.get("ВП") or 0)
    запас = float(r.get("Запас") or 0)
    влад = float(r.get("Владение") or 0)
    эп = float(r.get(ЭП) or 0)
    gm = r.get("GMROI")
    gm = float(gm) if pd.notna(gm) else None
    убыт = float(r.get("Убыток_цена") or 0)
    поз = int(r.get("Позиций_в_минус") or 0)
    дней = r.get("Дней_запаса_тек")
    дней = float(дней) if pd.notna(дней) and np.isfinite(дней) else None

    if оборот <= 0 and запас > 0:
        return ("Вывести целиком",
                "продаж нет вообще, а запас лежит и стоит %s ₽ в год" % _ц(влад),
                "высокая")
    if вп < 0:
        return ("Остановить продажи ниже себестоимости",
                "продано на %s ₽ при себестоимости %s ₽ — в минусе весь объект целиком, "
                "теряем на каждой продаже, а не на хранении" % (_ц(оборот), _ц(оборот - вп)),
                "срочная")
    if убыт > 0.25 * max(вп, 1):
        return ("Пересмотреть цены по убыточным позициям",
                "в целом плюс, но %d позиций продаются ниже себестоимости и съедают "
                "%s ₽ прибыли" % (поз, _ц(убыт)),
                "высокая")
    if gm is not None and gm < порог and запас > 0:
        хвост = (", запаса на %.0f дней" % дней) if дней else ""
        return ("Сократить запас или пересмотреть условия закупки",
                "рубль запаса приносит %.2f ₽ прибыли в год при пороге %.2f%s — "
                "содержание дороже отдачи" % (gm, порог, хвост),
                "средняя")
    if эп < 0:
        return ("Сократить запас",
                "прибыль %s ₽ в год не покрывает содержание %s ₽" % (_ц(вп), _ц(влад)),
                "средняя")
    return ("", "", "")


def решения(св: dict, факт: pd.DataFrame, cfg: dict, годовой: float, лог) -> pd.DataFrame | None:
    ставка = (float(cfg["экономика"]["ставка_хранения"])
              + float(cfg["экономика"]["ставка_капитала"]))
    порог = float(cfg["экономика"].get("порог_gmroi") or ставка)
    п = cfg.get("портфель", {})
    мин_запас = float(п.get("минимум_запаса_руб", 50000))
    мин_эффект = float(п.get("минимум_эффекта_руб", 20000))

    строки = []
    for уровень, ключ_св, keys, подпись in СЛОИ:
        g = св.get(ключ_св)
        if g is None or not len(g) or подпись not in g.columns:
            continue
        g = g.copy()
        уб = _убытки(факт, keys, cfg)
        общие = [k for k in keys if k in g.columns and (not len(уб) or k in уб.columns)]
        if len(уб) and общие:
            g = g.merge(уб, on=общие, how="left")
        g["Убыток_цена"] = g.get("Убыток_цена", pd.Series(0.0, index=g.index)).fillna(0)
        g["Позиций_в_минус"] = g.get("Позиций_в_минус", pd.Series(0, index=g.index)).fillna(0)

        for _, r in g.iterrows():
            запас = float(r.get("Запас") or 0)
            if запас < мин_запас and float(r.get("Убыток_цена") or 0) < мин_эффект:
                continue
            реш, обосн, срочн = _рек(r, порог)
            if not реш:
                continue
            # Что даст решение за год: прекращённый убыток от продаж ниже
            # себестоимости плюс содержание запаса, который перестанем держать.
            эффект = float(r.get("Убыток_цена") or 0) * годовой
            if реш in ("Вывести целиком", "Сократить запас",
                       "Сократить запас или пересмотреть условия закупки"):
                эффект += float(r.get("Владение") or 0)
            if эффект < мин_эффект:
                continue
            строки.append({
                "Уровень": уровень, "Объект": str(r.get(подпись)),
                "Решение": реш, "Срочность": срочн,
                "SKU": int(r.get("SKU") or 0),
                "Позиций в минус": int(r.get("Позиций_в_минус") or 0),
                "Оборот, ₽": float(r.get("Оборот") or 0),
                "Валовая прибыль, ₽": float(r.get("ВП") or 0),
                "Маржа": (float(r.get("Маржа_%")) / 100 if pd.notna(r.get("Маржа_%")) else None),
                "Запас, ₽": запас,
                "GMROI": (float(r.get("GMROI")) if pd.notna(r.get("GMROI")) else None),
                "Стоимость владения, ₽/год": float(r.get("Владение") or 0),
                "Прибыль за вычетом содержания, ₽/год": float(r.get(ЭП) or 0),
                "Убыток на цене, ₽/год": float(r.get("Убыток_цена") or 0) * годовой,
                "Эффект решения, ₽/год": эффект,
                "Обоснование": обосн,
                "Статус выполнения": "", "Комментарий": ""})

    if not строки:
        лог("   Портфель: убыточных объектов не найдено")
        return None
    t = pd.DataFrame(строки)
    поряд = {"срочная": 0, "высокая": 1, "средняя": 2}
    t["_с"] = t["Срочность"].map(поряд).fillna(3)
    t = (t.sort_values(["_с", "Эффект решения, ₽/год"], ascending=[True, False])
           .drop(columns="_с").reset_index(drop=True))
    # ВАЖНО: уровни вложены друг в друга — бренд внутри направления,
    # направление внутри склада. Складывать эффекты между уровнями нельзя:
    # это одни и те же деньги, увиденные с разных сторон. Поэтому общего
    # итога здесь нет, только по уровням.
    лог("   Портфель: %d решений (уровни вложены, общий итог не складывается)" % len(t))
    for у, g in t.groupby("Уровень"):
        лог("      %-14s %3d объектов | эффект %9.0f руб./год"
            % (у, len(g), g["Эффект решения, ₽/год"].sum()))
    return t
