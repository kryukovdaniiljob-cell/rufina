# -*- coding: utf-8 -*-
"""Самопроверка расчёта: сходятся ли числа между уровнями и листами.

Зачем. Отдельные формулы можно проверить глазами, а вот согласованность —
нет: свёртка по направлениям и свёртка по брендам считаются независимо, и
если одна из них поедет, в отчёте это выглядит нормально. За эту неделю
три ошибки нашлись именно так: сумма по позициям не совпадала с итогом.

Проверки идут при каждом запуске. Расхождение больше копейки печатается
в журнал заглавными буквами и попадает на лист «00c.Самопроверка».
"""
from __future__ import annotations
import numpy as np
import pandas as pd

ДОПУСК = 1.0          # рубль: копеечные хвосты округления нас не волнуют


def _сумма(g, c):
    return float(g[c].sum()) if g is not None and c in g.columns else None


def _строка(имя, ожидалось, получилось, пояснение=""):
    расх = (abs(ожидалось - получилось)
            if ожидалось is not None and получилось is not None else None)
    ок = расх is not None and расх <= ДОПУСК
    return {"Проверка": имя, "Ожидалось": ожидалось, "Получилось": получилось,
            "Расхождение": расх, "Итог": "ок" if ок else "РАСХОЖДЕНИЕ",
            "Что это значит": пояснение}


def _сверка_с_источником(р: list, d, mine, св: dict) -> None:
    """Отчёт против ПЕРВОИСТОЧНИКА, а не против самого себя.

    Все остальные проверки сверяют отчёт с отчётом: свёртку с итогом, итог
    со сводкой. Такая проверка не заметит ошибку, сделанную один раз на
    входе: она честно разойдётся по всем уровням и везде сойдётся сама
    с собой. Здесь мы возвращаемся к выгрузке сквозной аналитики и
    складываем исходные строки продаж и стока по своим НС-кодам.
    """
    if d is None or mine is None:
        return
    sku = св.get("L6_SKU")
    if sku is None or not len(sku):
        return
    пр = d.get("продажи")
    if пр is not None and len(пр):
        с = пр[пр["НС-Код"].isin(mine)]
        for ист, отч, имя in (("Оборот", "Оборот", "оборот"),
                              ("Продажи себ", "Себест", "себестоимость продаж"),
                              ("Продажи профит", "ВП", "валовая прибыль"),
                              ("Продажи кол", "Штук", "продано штук")):
            if ист not in с.columns:
                continue
            р.append(_строка("Сквозная -> отчёт: %s" % имя,
                             float(pd.to_numeric(с[ист], errors="coerce").sum()),
                             _сумма(sku, отч),
                             "сумма исходных строк продаж по своим НС-кодам"))
    ст = d.get("сток_тек")
    if ст is not None and len(ст) and "Общая себ-ть запасов" in ст.columns:
        с = ст[ст["НС-Код"].isin(mine)]
        р.append(_строка("Сквозная -> отчёт: запас",
                         float(pd.to_numeric(с["Общая себ-ть запасов"],
                                             errors="coerce").sum()),
                         _сумма(sku, "Запас"),
                         "сумма исходных строк текущего стока по своим НС-кодам"))


def проверить(св: dict, S: dict, списки: dict, cfg: dict, лог,
              d=None, mine=None) -> pd.DataFrame:
    р = []
    _сверка_с_источником(р, d, mine, св)
    УРОВНИ = ["L1_Группа планирования", "L2_Направление", "L3_Группа 1",
              "L4_Группа 2", "L5_Группа 3", "L6_SKU"]
    есть = [u for u in УРОВНИ if u in св and св[u] is not None and len(св[u])]

    # 1. Одни и те же деньги на всех уровнях дерева. Если свёртка теряет
    #    или задваивает строки, это вылезет здесь и больше нигде.
    for кол, имя in (("Оборот", "оборот"), ("Запас", "запас"),
                     ("Владение", "стоимость владения"),
                     ("Эконом_прибыль", "прибыль за вычетом содержания")):
        знач = [_сумма(св[u], кол) for u in есть]
        знач = [z for z in знач if z is not None]
        if len(знач) < 2:
            continue
        р.append(_строка("Уровни дерева: %s" % имя, знач[0],
                         знач[int(np.argmax([abs(z - знач[0]) for z in знач]))],
                         "все шесть уровней должны давать одно число"))

    # 2. Арифметика прибыли на каждом уровне: годовая ВП минус владение.
    for u in есть:
        g = св[u]
        if not {"ВП_год", "Владение", "Эконом_прибыль"} <= set(g.columns):
            continue
        ож = float((g["ВП_год"] - g["Владение"]).sum())
        р.append(_строка("Арифметика прибыли: %s" % u.split("_", 1)[-1],
                         ож, float(g["Эконом_прибыль"].sum()),
                         "ВП за год − стоимость владения = прибыль за вычетом содержания"))
        break                      # достаточно одного уровня: формула общая

    # 3. Сводка против самого детального уровня.
    sku = св.get("L6_SKU")
    for ключ, кол, имя in (("оборот", "Оборот", "оборот"), ("запас", "Запас", "запас"),
                           ("владение", "Владение", "стоимость владения"),
                           ("эконом_прибыль", "Эконом_прибыль", "прибыль за вычетом содержания")):
        if ключ in S and sku is not None:
            р.append(_строка("Сводка = сумма по позициям: %s" % имя,
                             float(S[ключ]), _сумма(sku, кол),
                             "цифра на титуле должна совпадать с суммой строк"))

    # 4. GMROI сводки на том же знаменателе, что и стоимость владения.
    if sku is not None and "ставка" in S and S.get("ставка"):
        база = _сумма(sku, "Владение") / float(S["ставка"])
        вп = _сумма(sku, "ВП_год")
        if база and вп is not None:
            р.append(_строка("GMROI сводки", float(S["gmroi"]) * база, вп,
                             "GMROI x база должно давать годовую валовую прибыль"))

    # 5. План работ: одна позиция не должна стоять в противоречивых действиях.
    зд = списки.get("задачи")
    прот = 0
    if зд is not None and len(зд) and "Действие" in зд.columns:
        о = зд[зд["НС-Код"].astype(str).str.startswith("НС-")]
        пары = о.groupby("НС-Код")["Действие"].apply(lambda s: set(s))
        плохие = {("Уценить", "Дозаказать"), ("Уценить", "Переместить"),
                  ("Вывести", "Дозаказать"), ("Вывести", "Переместить")}
        прот = sum(1 for v in пары if any(a in v and b in v for a, b in плохие))
    р.append(_строка("План работ: противоречивые пары действий", 0.0, float(прот),
                     "уценивать и одновременно дозаказывать одну позицию нельзя"))

    t = pd.DataFrame(р)
    плохо = t[t["Итог"] != "ок"]
    if len(плохо):
        лог("")
        лог("   " + "!" * 66)
        лог("   САМОПРОВЕРКА НАШЛА РАСХОЖДЕНИЯ - цифрам в отчёте верить нельзя:")
        for _, r in плохо.iterrows():
            лог("   %-46s расхождение %s"
                % (r["Проверка"], ("%.2f руб." % r["Расхождение"])
                   if r["Расхождение"] is not None else "не удалось посчитать"))
        лог("   " + "!" * 66)
    else:
        лог("   Самопроверка: %d проверок пройдено, расхождений нет" % len(t))
    return t
