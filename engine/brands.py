# -*- coding: utf-8 -*-
"""Лист «Бренды по группам»: контракт как единица решения.

Логика не наша, а категорийного менеджера: смотрим не на позицию, а на
БРЕНД ВНУТРИ ГРУППЫ — это и есть контракт с поставщиком. По каждому такому
контракту собираем продажи двумя полугодиями, прибыль, долю в обороте,
текущий сток и две рентабельности, а дальше предлагаем вывод и мероприятие.

Вывод и мероприятие — заготовка, а не приговор: колонки открыты на
редактирование, менеджер правит формулировку под то, что знает о рынке.
"""
from __future__ import annotations
import numpy as np
import pandas as pd

КЛЮЧИ = ["Группа 2", "Бренд"]


def _ц(v) -> str:
    try:
        return format(int(round(float(v))), ",d").replace(",", chr(160))
    except (TypeError, ValueError):
        return "0"


def _вывод(r, порог_доли: float, порог_рент: float) -> tuple[str, str]:
    """Вывод по контракту и мероприятие. Пороги — в настройках.

    Порядок проверок важен: сначала то, что решается однозначно (минус,
    отсутствие спроса), потом оттенки."""
    доля = float(r.get("Доля_оборота_%") or 0)
    вп = float(r.get("ВП") or 0)
    рент = r.get("Рент_без_непрямых_%")
    рент = float(рент) if pd.notna(рент) else None
    оборот = float(r.get("Оборот") or 0)
    сток = float(r.get("Запас") or 0)
    штук = float(r.get("Штук") or 0)
    дней = r.get("Дней_запаса_тек")
    дней = float(дней) if pd.notna(дней) and np.isfinite(дней) else None
    рост = r.get("Рост_2п_%")
    рост = float(рост) if pd.notna(рост) else None

    if вп < 0:
        return ("Убыточный контракт: продаём дешевле, чем покупаем",
                "Закрыть контракт или пересмотреть закупочные цены")
    if оборот <= 0 and сток > 0:
        return ("Спроса нет вообще, сток лежит",
                "Распродать сток, не докупать")
    if рент is not None and рент < 0 and сток > 0:
        return ("Отрицательная рентабельность: содержание съедает прибыль",
                "Распродать сток; дальше возить под заказ")
    if доля >= порог_доли and рент is not None and рент >= порог_рент:
        return ("Крупный и эффективный контракт — опора портфеля",
                "Делать фокус на продажи, увеличивать глубину")
    if доля >= порог_доли:
        return ("Крупный контракт при слабой рентабельности",
                "Пересмотреть условия закупки и логистики")
    if рент is not None and рент >= порог_рент and доля < порог_доли:
        return ("Небольшой, но рентабельный контракт",
                "Оставить в портфеле, контролировать сток")
    if сток > 0 and дней is not None and дней > 365:
        return ("Сток на год вперёд при низком спросе",
                "Распродать сток, не докупать, оставить под заказ")
    if сток <= 0 and оборот > 0:
        return ("Продаётся без склада",
                "Возить под заказ")
    if рост is not None and рост > 20:
        return ("Продажи растут во втором полугодии",
                "Развивать продажи")
    return ("Низкий спрос и невысокая рентабельность",
            "Возить под заказ")


def бренды_по_группам(св: dict, sku: pd.DataFrame, cfg: dict, годовой: float, лог) -> pd.DataFrame | None:
    g = св.get("G2_Бренд")
    if g is None or not len(g):
        лог("   ! Разрез «группа × бренд» не собран — лист пропущен")
        return None
    п = cfg.get("бренды", {})
    мин_оборот = float(п.get("минимум_оборота_руб", 30000))
    мин_сток = float(п.get("минимум_стока_руб", 30000))
    порог_доли = float(п.get("крупный_контракт_доля_%", 3.0))
    порог_рент = float(п.get("хорошая_рентабельность_%", 5.0))

    t = g.copy()
    # Мелочь не выносим: по контракту на 2 тысячи решение не принимают.
    t = t[(t["Оборот"] >= мин_оборот) | (t["Запас"] >= мин_сток)]
    if not len(t):
        лог("   ! Контрактов выше порога нет — лист пропущен")
        return None

    for c in ("Оборот_1п", "Оборот_2п", "Себест_1п", "Себест_2п",
              "ВП_1п", "ВП_2п", "Штук_1п", "Штук_2п"):
        if c not in t.columns:
            t[c] = 0.0

    общий = float(t["Оборот"].sum()) or 1.0
    t["Доля_оборота_%"] = 100 * t["Оборот"] / общий
    # Рентабельность БЕЗ НЕПРЯМЫХ ЗАТРАТ: валовая прибыль за год минус
    # стоимость владения запасом, отнесённая к обороту за год. Непрямые
    # затраты (офис, зарплаты, общая логистика) сюда не входят.
    # Знаменатель — только положительный оборот. При обороте в минусе
    # (возвратов больше, чем продаж) отношение переворачивает знак:
    # убыточный контракт показывал рентабельность +469 %.
    об_год = (t["Оборот"] * годовой).where(t["Оборот"] > 0)
    t["Рент_без_непрямых_%"] = 100 * (t["ВП"] * годовой - t["Владение"]) / об_год
    # Общая рентабельность — из юнит-экономики: там учтены все затраты,
    # включая непрямые. Если выгрузки нет, колонка просто не появится.
    if sku is not None and "ЮЭ_результат" in sku.columns and set(КЛЮЧИ) <= set(sku.columns):
        ю = (sku.groupby(КЛЮЧИ, as_index=False, observed=True, dropna=False)
             ["ЮЭ_результат"].sum())
        t = t.merge(ю, on=КЛЮЧИ, how="left")
        t["ЮЭ_рентабельность_%"] = 100 * t["ЮЭ_результат"] / об_год

    t["Рост_2п_%"] = np.where(t["Оборот_1п"] > 0,
                              100 * (t["Оборот_2п"] / t["Оборот_1п"].replace(0, np.nan) - 1),
                              np.nan)

    выводы = t.apply(lambda r: _вывод(r, порог_доли, порог_рент), axis=1)
    t["Вывод по контракту"] = [x[0] for x in выводы]
    t["Мероприятия"] = [x[1] for x in выводы]

    ПОРЯДОК = [
        ("Группа 2", "Группа"), ("Бренд", "Бренд"), ("SKU", "SKU"),
        ("Штук_1п", "Продажи 1 полугодие, ед."),
        ("Оборот_1п", "Продажи 1 полугодие, ₽"),
        ("Штук_2п", "Продажи 2 полугодие, ед."),
        ("Оборот_2п", "Продажи 2 полугодие, ₽"),
        ("Рост_2п_%", "Рост 2п к 1п"),
        ("Штук", "Продажи всего, ед."),
        ("Себест", "Продажи в ценах себестоимости, ₽"),
        ("Оборот", "Оборот (выручка), ₽"),
        ("Доля_оборота_%", "Доля в обороте"),
        ("ВП_1п", "Валовая прибыль 1 полугодие, ₽"),
        ("ВП_2п", "Валовая прибыль 2 полугодие, ₽"),
        ("ВП", "Валовая прибыль всего, ₽"),
        ("Маржа_%", "Профит (маржа)"),
        ("Запас_ед", "Сток текущий, ед."),
        ("Запас", "Сток текущий, ₽"),
        ("Дней_запаса_тек", "Дней запаса"),
        ("Владение", "Стоимость владения, ₽/год"),
        ("Рент_без_непрямых_%", "Рентабельность без непрямых затрат"),
        ("ЮЭ_рентабельность_%", "Общая рентабельность (юнит-экономика)"),
        ("Вывод по контракту", "Вывод по контракту"),
        ("Мероприятия", "Мероприятия"),
    ]
    есть = [(k, n) for k, n in ПОРЯДОК if k in t.columns]
    out = t[[k for k, _ in есть]].copy()
    out.columns = [n for _, n in есть]
    out = out.sort_values(["Группа", "Оборот (выручка), ₽"], ascending=[True, False])
    out["Комментарий менеджера"] = ""

    лог("   Бренды по группам: %d контрактов, %d групп, оборот %.2f млн руб."
        % (len(out), out["Группа"].nunique(), out["Оборот (выручка), ₽"].sum() / 1e6))
    минус = out[out["Валовая прибыль всего, ₽"] < 0]
    if len(минус):
        лог("      из них убыточных: %d на %.2f млн руб. оборота"
            % (len(минус), минус["Оборот (выручка), ₽"].sum() / 1e6))
    return out
