def бренды_по_группам(св: dict, sku: pd.DataFrame, cfg: dict, годовой: float, лог) -> pd.DataFrame | None:
    g = св.get("G2_Бренд")
    if g is None or not len(g):
        лог("   ! Разрез «группа × бренд» не собран — лист пропущен")
        return None
    п = cfg.get("бренды", {})
    мин_оборот = float(п.get("минимум_оборота_руб", 30000))
    мин_сток = float(п.get("минимум_стока_руб", 30000))
    порог_доли = float(п.get("крупный_контракт_доля_в_группе_%", 15.0))
    порог_рент = float(п.get("хорошая_рентабельность_%", 5.0))
    слова = [str(x).strip().lower() for x in (п.get("фокус_группы") or []) if str(x).strip()]
    подписи = {str(k).strip().lower(): str(v)
               for k, v in (п.get("названия_фокус_групп") or {}).items()}
    исключения = {str(k).strip().lower(): [str(x).strip().lower() for x in (v or [])]
                  for k, v in (п.get("исключения_фокус_групп") or {}).items()}
    область = {str(k).strip().lower(): str(v).strip().lower()
               for k, v in (п.get("область_фокус_групп") or {}).items()}
    # Уровень блоков. Если фокус-слова заданы — блоки по ним; если нет,
    # группируем по колонке из настроек: у одного менеджера это товарное
    # направление, у другого — подгруппа. Структуры периметров разные.
    колонка = str(п.get("колонка_группы", "Товарное направление"))

    t = g.copy()
    if "ЮЭ_результат" not in t.columns and sku is not None \
            and "ЮЭ_результат" in sku.columns:
        # Юнит-экономика живёт на уровне позиции — поднимаем её ПО ТОМУ ЖЕ
        # ключу, по которому собран разрез. Раньше свод шёл по одному
        # «Бренду»: результат бренда по всей компании приписывался КАЖДОЙ
        # строке «направление × группа 1 × группа 2 × бренд», а потом ещё и
        # складывался. У одного бренда так набегало 24 копии, по листу
        # юнит-экономика была завышена в 31 раз и местами меняла знак —
        # у «Трубы / TEBO» вместо +437 тыс. ₽ выходило −7,0 млн ₽.
        ключ = [c for c in ("Товарное направление", "Группа 1", "Группа 2", "Бренд")
                if c in t.columns and c in sku.columns]
        if ключ:
            ю = sku.copy()
            for c in ключ:
                ю[c] = ю[c].astype(str)
            ю = ю.groupby(ключ, as_index=False, observed=True,
                          dropna=False)["ЮЭ_результат"].sum()
            for c in ключ:
                t[c + "_к"] = t[c].astype(str)
            ю.columns = [c + "_к" for c in ключ] + ["ЮЭ_результат"]
            t = t.merge(ю, on=[c + "_к" for c in ключ], how="left")
            t = t.drop(columns=[c + "_к" for c in ключ])
            прив = float(pd.to_numeric(t["ЮЭ_результат"], errors="coerce").sum())
            итог = float(pd.to_numeric(sku["ЮЭ_результат"], errors="coerce").sum())
            лог("   Юнит-экономика поднята по ключу «%s»: %.2f млн руб. "
                "из %.2f млн по периметру" % (" × ".join(ключ), прив / 1e6, итог / 1e6))
        else:
            лог("   ! Юнит-экономику не к чему привязать — колонка пропущена")

    if слова:
        t["_фокус"] = [_фокус(a, b, слова, исключения, область)
                       for a, b in zip(t.get("Группа 1", ""), t["Группа 2"])]
        было = len(t)
        t = t[t["_фокус"] != ""]
        лог("   Фокус-группы (%s): отобрано %d строк из %d"
            % (", ".join(слова), len(t), было))
        for с in слова:
            где = область.get(с, "оба")
            нет = исключения.get(с) or []
            if где != "оба" or нет:
                лог("      «%s»: ищем в %s%s"
                    % (с, {"г1": "«Группа 1»", "г2": "«Группа 2»"}.get(где, "обеих группах"),
                       (", кроме: " + ", ".join(нет)) if нет else ""))
        пусто = [с for с in слова if с not in set(t["_фокус"])]
        if пусто:
            лог("      ! ничего не подошло под слова: %s — блоков не будет"
                % ", ".join(пусто))
    else:
        если_есть = колонка if колонка in t.columns else "Группа 2"
        t["_фокус"] = t[если_есть].astype(str)
        лог("   Блоки по колонке «%s»: %d значений"
            % (если_есть, t["_фокус"].nunique()))
    if not len(t):
        лог("   ! Под фокус-группы ничего не подошло — лист пропущен")
        return None

    for c in СУММЫ:
        if c not in t.columns:
            t[c] = 0.0
        t[c] = pd.to_numeric(t[c], errors="coerce").fillna(0)

    # Бренд внутри фокус-группы — одна строка, без дробления по подгруппам.
    бренды = t.groupby(["_фокус", "Бренд"], as_index=False, observed=True,
                       dropna=False)[СУММЫ].sum()
    группы = t.groupby(["_фокус"], as_index=False, observed=True, dropna=False)[СУММЫ].sum()

    общий = float(группы["Оборот"].sum()) or 1.0
    все_бренды = бренды.copy()          # до отсечки мелочи: для лидера и концентрации
    бренды = _производные(бренды, годовой, общий, мин_оборот)
    группы = _производные(группы, годовой, общий, мин_оборот)

    # Мелочь не выбрасываем, а сворачиваем в одну строку на группу: иначе
    # доли внутри группы не сложатся в 100 % и колонке нельзя верить.
    мелкие = ~((бренды["Оборот"] >= мин_оборот) | (бренды["Запас"] >= мин_сток))
    прочие = None
    if int(мелкие.sum()):
        х = бренды[мелкие]
        скол = х.groupby("_фокус", as_index=False, observed=True, dropna=False).size()
        прочие = х.groupby("_фокус", as_index=False, observed=True, dropna=False)[СУММЫ].sum()
        прочие = _производные(прочие, годовой, общий, мин_оборот)
        прочие = прочие.merge(скол, on="_фокус", how="left")
        прочие["Наименование"] = ["Прочие мелкие контракты (%d)" % n for n in прочие["size"]]
        прочие["Бренд"] = прочие["Наименование"]
        лог("      мелочь ниже порога свёрнута: %d контрактов в %d строк"
            % (int(мелкие.sum()), len(прочие)))
    бренды = бренды[~мелкие].copy()

    # Доля ВНУТРИ группы. Знаменатель — итог группы целиком, включая
    # свёрнутую мелочь, поэтому видимые строки складываются ровно в 100 %.
    итог = группы.set_index("_фокус")["Оборот"]
    for df in (бренды, прочие):
        if df is None or not len(df):
            continue
        зн = pd.to_numeric(df["_фокус"].map(итог), errors="coerce")
        df["Доля_в_группе_%"] = 100 * df["Оборот"] / зн.where(зн > 0)
    группы["Доля_в_группе_%"] = 100.0

    в = list(бренды.apply(lambda r: _вывод(r, порог_доли, порог_рент), axis=1)) \
        if len(бренды) else []
    бренды["Вывод по контракту"] = [x[0] for x in в]
    бренды["Мероприятия"] = [x[1] for x in в]
    бренды["Уровень"] = 2
    бренды["Наименование"] = бренды["Бренд"].astype(str)
    if прочие is not None:
        прочие["Вывод по контракту"] = (
            "контракты ниже порога (%s ₽ оборота / %s ₽ стока); "
            "по отдельности разбирать дороже, чем результат"
            % (_ц(мин_оборот), _ц(мин_сток)))
        прочие["Мероприятия"] = "Разбирать пакетом, а не по одному"
        прочие["Уровень"] = 2

    # Итог по группе. Лидер и число контрактов считаются от ВСЕХ брендов
    # группы, включая свёрнутую мелочь, — иначе концентрация выйдет выше
    # настоящей, а «контрактов» меньше, чем есть на самом деле.
    гв = []
    for _, гр in группы.iterrows():
        д = все_бренды[все_бренды["_фокус"] == гр["_фокус"]]
        лид, дл = "", 0.0
        об_гр = float(гр["Оборот"])
        if len(д) and об_гр > 0:
            с = д.loc[д["Оборот"].idxmax()]
            лид, дл = str(с["Бренд"]), 100 * float(с["Оборот"]) / об_гр
        уб = д[д["ВП"] < 0]
        гв.append(_вывод_группы(гр, лид, дл, len(д), len(уб),
                                float(уб["Оборот"].sum()), порог_рент))
    группы["Вывод по контракту"] = [x[0] for x in гв]
    группы["Мероприятия"] = [x[1] for x in гв]
    группы["Уровень"] = 1
    группы["Наименование"] = [подписи.get(x, str(x).upper()) + " — общий итог"
                              for x in группы["_фокус"]]

    строки = []
    for _, гр in группы.sort_values("Оборот", ascending=False).iterrows():
        строки.append(гр)
        дети = бренды[бренды["_фокус"] == гр["_фокус"]].sort_values("Оборот", ascending=False)
        строки.extend(r for _, r in дети.iterrows())
        if прочие is not None:
            # мелочь всегда последней строкой блока, а не в общем рейтинге
            строки.extend(r for _, r in прочие[прочие["_фокус"] == гр["_фокус"]].iterrows())
    out = pd.DataFrame(строки)

    есть = [(k, n) for k, n in ПОРЯДОК if k in out.columns]
    out = out[[k for k, _ in есть]].copy()
    out.columns = [n for _, n in есть]
    out["Комментарий менеджера"] = ""

    лог("   Бренды по группам: %d групп, %d контрактов, оборот %.2f млн руб."
        % (len(группы), len(бренды), группы["Оборот"].sum() / 1e6))
    for _, гр in группы.sort_values("Оборот", ascending=False).iterrows():
        лог("      %-26s %8.2f млн руб.  доля %5.1f %%"
            % (гр["Наименование"], гр["Оборот"] / 1e6, гр["Доля_оборота_%"]))
    минус = бренды[бренды["ВП"] < 0]
    if len(минус):
        лог("      убыточных контрактов: %d на %.2f млн руб. оборота"
            % (len(минус), минус["Оборот"].sum() / 1e6))
    return out
