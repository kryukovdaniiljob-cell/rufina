# -*- coding: utf-8 -*-
"""Лист «Бренды по группам»: контракт как единица решения.

Логика не наша, а категорийного менеджера: смотрим не на позицию, а на
БРЕНД ВНУТРИ ГРУППЫ — это и есть контракт с поставщиком. По каждому такому
контракту собираем продажи двумя полугодиями, прибыль, долю в обороте,
текущий сток, спрос и две рентабельности, а дальше предлагаем вывод
и мероприятие.

Вывод и мероприятие — заготовка, а не приговор: колонки открыты на
редактирование, менеджер правит формулировку под то, что знает о рынке.

Про «спрос». Внешних данных о рынке у нас нет — ни доли, ни продаж
конкурентов. Спрос оцениваем по своим следам: сколько сделок, как растут
продажи во втором полугодии и сколько мы упустили, пока товара не было
на складе. Это спрос НА НАС, а не доля рынка, и так и подписано.
"""
from __future__ import annotations
import numpy as np
import pandas as pd

КЛЮЧИ = ["Группа 1", "Группа 2", "Бренд"]


def _ц(v) -> str:
    try:
        return format(int(round(float(v))), ",d").replace(",", chr(160))
    except (TypeError, ValueError):
        return "0"


def _ч(v, зам=None):
    """Число или замена: ловит и None, и NaN, и бесконечность."""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return зам
    return зам if not np.isfinite(f) else f


def _спрос(r) -> tuple[str, bool]:
    """Что видно про спрос и есть ли признак, что он выше наших продаж."""
    сделок = _ч(r.get("Строк"), 0) or 0
    рост = _ч(r.get("Рост_2п_%"))
    oos = _ч(r.get("OOS_%"), 0) or 0
    упущ = _ч(r.get("Упущено"), 0) or 0

    части = []
    if сделок:
        части.append("%s сделок" % _ц(сделок))
    if рост is not None:
        части.append("2п к 1п %+.0f%%" % рост)
    # Дефицит — единственный намёк на спрос ВЫШЕ того, что мы продали:
    # позиция кончалась, значит покупатель приходил и уходил ни с чем.
    голод = oos >= 20 and упущ > 0
    if голод:
        части.append("нет на складе %.0f%% времени, упущено %s ₽" % (oos, _ц(упущ)))
    return ("; ".join(части), голод)


def _вывод(r, порог_доли: float, порог_рент: float) -> tuple[str, str]:
    """Вывод по контракту и мероприятие.

    Собирается из фактов, а не выбирается из готовых фраз: сначала
    экономика (прибыль, рентабельность), потом спрос, потом действие.
    """
    доля = _ч(r.get("Доля_оборота_%"), 0) or 0
    вп = _ч(r.get("ВП"), 0) or 0
    рент = _ч(r.get("Рент_без_непрямых_%"))
    марж = _ч(r.get("Маржа_%"))
    оборот = _ч(r.get("Оборот"), 0) or 0
    сток = _ч(r.get("Запас"), 0) or 0
    дней = _ч(r.get("Дней_запаса_тек"))
    рост = _ч(r.get("Рост_2п_%"))
    текст_спроса, голод = _спрос(r)

    эк = []
    if марж is not None:
        эк.append("профит %.0f%%" % марж)
    if рент is not None:
        эк.append("рентабельность без непрямых %.0f%%" % рент)
    эк = ", ".join(эк)

    def собрать(суть, действие):
        куски = [суть]
        if эк:
            куски.append(эк)
        if текст_спроса:
            куски.append(текст_спроса)
        return ("; ".join(куски), действие)

    # 1. Деньги теряются на каждой продаже — это важнее всего остального.
    if вп < 0:
        return собрать("убыточный контракт: продаём дешевле, чем покупаем",
                       "Закрыть контракт или пересмотреть закупочные цены")
    # 2. Спроса нет вообще, а склад занят.
    if оборот <= 0 and сток > 0:
        return собрать("продаж нет, сток лежит",
                       "Распродать сток, не докупать")
    # 3. Прибыль есть, но содержание запаса её съедает.
    if рент is not None and рент < 0 and сток > 0:
        д = (", запаса на %.0f дней" % дней) if дней else ""
        return собрать("содержание запаса съедает прибыль" + д,
                       "Сократить сток; дальше возить под заказ")
    # 4. Спрос выше наших продаж — теряем на отсутствии товара.
    if голод and вп > 0:
        return собрать("спрос выше наших продаж, товара не хватает",
                       "Дозаказать и поднять норму запаса")
    # 5. Крупный контракт: опора портфеля или предмет переговоров.
    if доля >= порог_доли:
        если_хорош = рент is not None and рент >= порог_рент
        return собрать(
            "крупный контракт, доля в обороте %.1f%%" % доля,
            "Делать фокус на продажи, увеличивать глубину" if если_хорош
            else "Пересмотреть условия закупки и логистики")
    # 6. Растёт — есть на что опереться.
    if рост is not None and рост >= 20 and вп > 0:
        return собрать("продажи растут", "Развивать: расширить ассортимент бренда")
    # 7. Падает при живой экономике.
    if рост is not None and рост <= -30:
        return собрать("продажи падают",
                       "Разобраться с причиной падения; сток не наращивать")
    # 8. Маленький, но здоровый.
    if рент is not None and рент >= порог_рент:
        return собрать("небольшой, но рентабельный контракт",
                       "Оставить в портфеле, контролировать сток")
    # 9. Продаётся без склада — идеальная схема, не ломать.
    if сток <= 0 and оборот > 0:
        return собрать("продаётся без склада", "Возить под заказ")
    if сток > 0 and дней is not None and дней > 365:
        return собрать("сток на год вперёд при низком спросе",
                       "Распродать сток, не докупать, оставить под заказ")
    return собрать("низкий спрос и невысокая рентабельность", "Возить под заказ")


def _фокус(r, слова: list[str]) -> str:
    """Какое из ключевых слов поймало эту строку. Пусто — не фокусная."""
    г1 = str(r.get("Группа 1") or "").lower()
    г2 = str(r.get("Группа 2") or "").lower()
    нашли = [с for с in слова if с in г1 or с in г2]
    return ", ".join(нашли)


def бренды_по_группам(св: dict, sku: pd.DataFrame, cfg: dict, годовой: float, лог) -> pd.DataFrame | None:
    g = св.get("G2_Бренд")
    if g is None or not len(g):
        лог("   ! Разрез «группа × бренд» не собран — лист пропущен")
        return None
    п = cfg.get("бренды", {})
    мин_оборот = float(п.get("минимум_оборота_руб", 30000))
    мин_сток = float(п.get("минимум_стока_руб", 30000))
    порог_доли = float(п.get("крупный_контракт_доля_%", 3.0))
    порог_рент = float(п.get("хорошая_рентабельность_%", 5.0))
    слова = [str(x).strip().lower() for x in (п.get("фокус_группы") or []) if str(x).strip()]

    t = g.copy()
    if слова:
        t["Фокус"] = t.apply(lambda r: _фокус(r, слова), axis=1)
        было = len(t)
        t = t[t["Фокус"] != ""]
        лог("   Фокус-группы (%s): отобрано %d строк из %d"
            % (", ".join(слова), len(t), было))
    # Мелочь не выносим: по контракту на две тысячи решение не принимают.
    t = t[(t["Оборот"] >= мин_оборот) | (t["Запас"] >= мин_сток)]
    if not len(t):
        лог("   ! Контрактов выше порога нет — лист пропущен")
        return None

    for c in ("Оборот_1п", "Оборот_2п", "Себест_1п", "Себест_2п",
              "ВП_1п", "ВП_2п", "Штук_1п", "Штук_2п"):
        if c not in t.columns:
            t[c] = 0.0

    общий = float(t["Оборот"].sum()) or 1.0
    t["Доля_оборота_%"] = 100 * t["Оборот"] / общий
    # Рентабельность БЕЗ НЕПРЯМЫХ ЗАТРАТ: валовая прибыль за год минус
    # стоимость владения запасом, отнесённая к обороту за год. Непрямые
    # затраты (офис, зарплаты, общая логистика) сюда не входят.
    # Знаменатель — только положительный оборот: при обороте в минусе
    # отношение переворачивает знак, и убыточный контракт показывал +469 %.
    об_год = (t["Оборот"] * годовой).where(t["Оборот"] > 0)
    t["Рент_без_непрямых_%"] = 100 * (t["ВП"] * годовой - t["Владение"]) / об_год
    if sku is not None and "ЮЭ_результат" in sku.columns and set(КЛЮЧИ) <= set(sku.columns):
        ю = (sku.groupby(КЛЮЧИ, as_index=False, observed=True, dropna=False)
             ["ЮЭ_результат"].sum())
        t = t.merge(ю, on=КЛЮЧИ, how="left")
        t["ЮЭ_рентабельность_%"] = 100 * t["ЮЭ_результат"] / об_год

    t["Рост_2п_%"] = np.where(t["Оборот_1п"] > 0,
                              100 * (t["Оборот_2п"] / t["Оборот_1п"].replace(0, np.nan) - 1),
                              np.nan)

    выводы = t.apply(lambda r: _вывод(r, порог_доли, порог_рент), axis=1)
    t["Вывод по контракту"] = [x[0] for x in выводы]
    t["Мероприятия"] = [x[1] for x in выводы]

    ПОРЯДОК = [
        ("Фокус", "Фокус-группа"),
        ("Группа 1", "Группа 1"), ("Группа 2", "Группа"), ("Бренд", "Бренд"), ("SKU", "SKU"),
        ("Штук_1п", "Продажи 1 полугодие, ед."),
        ("Оборот_1п", "Продажи 1 полугодие, ₽"),
        ("Штук_2п", "Продажи 2 полугодие, ед."),
        ("Оборот_2п", "Продажи 2 полугодие, ₽"),
        ("Рост_2п_%", "Рост 2п к 1п"),
        ("Штук", "Продажи всего, ед."),
        ("Себест", "Продажи в ценах себестоимости, ₽"),
        ("Оборот", "Оборот (выручка), ₽"),
        ("Доля_оборота_%", "Доля в обороте"),
        ("ВП_1п", "Валовая прибыль 1 полугодие, ₽"),
        ("ВП_2п", "Валовая прибыль 2 полугодие, ₽"),
        ("ВП", "Валовая прибыль всего, ₽"),
        ("Маржа_%", "Профит (маржа)"),
        ("Строк", "Сделок за период"),
        ("OOS_%", "Нет на складе, % времени"),
        ("Упущено", "Упущено продаж, ₽"),
        ("Запас_ед", "Сток текущий, ед."),
        ("Запас", "Сток текущий, ₽"),
        ("Дней_запаса_тек", "Дней запаса"),
        ("Владение", "Стоимость владения, ₽/год"),
        ("Рент_без_непрямых_%", "Рентабельность без непрямых затрат"),
        ("ЮЭ_рентабельность_%", "Общая рентабельность (юнит-экономика)"),
        ("Вывод по контракту", "Вывод по контракту"),
        ("Мероприятия", "Мероприятия"),
    ]
    есть = [(k, n) for k, n in ПОРЯДОК if k in t.columns]
    out = t[[k for k, _ in есть]].copy()
    out.columns = [n for _, n in есть]
    сорт = ["Фокус-группа", "Группа"] if "Фокус-группа" in out.columns else ["Группа"]
    out = out.sort_values(сорт + ["Оборот (выручка), ₽"],
                          ascending=[True] * len(сорт) + [False])
    out["Комментарий менеджера"] = ""

    лог("   Бренды по группам: %d контрактов, %d групп, оборот %.2f млн руб."
        % (len(out), out["Группа"].nunique(), out["Оборот (выручка), ₽"].sum() / 1e6))
    минус = out[out["Валовая прибыль всего, ₽"] < 0]
    if len(минус):
        лог("      убыточных: %d на %.2f млн руб. оборота"
            % (len(минус), минус["Оборот (выручка), ₽"].sum() / 1e6))
    return out
