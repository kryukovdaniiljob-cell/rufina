# -*- coding: utf-8 -*-
"""Лист «Бренды по группам»: контракт как единица решения.

Смотрим не на позицию, а на БРЕНД ВНУТРИ ФОКУС-ГРУППЫ — это и есть
контракт с поставщиком. Бренд НЕ дробится по подгруппам: BAXI продаётся
в «Котлах», «Котлах газовых» и «Котлах электрических», но решение по
контракту принимается одно, значит и строка нужна одна.

Лист двухуровневый и сворачивается плюсами слева:
    КОТЛЫ — общий итог          <- сумма по всей фокус-группе
        BAXI                    <- контракт
        Navien
    НАСОСЫ — общий итог
        BELAMOS

Две доли, и они отвечают на разные вопросы. «Доля в обороте листа» —
насколько крупен блок в портфеле. «Доля внутри группы» — насколько бренд
держит СВОЮ категорию: бренд с 2 % листа может быть половиной небольшой
группы, и разговор с поставщиком ведётся именно от неё.

Мелочь ниже порога не выбрасывается, а сворачивается в строку «Прочие
мелкие контракты» — иначе доли внутри группы не складывались бы в 100 %
и колонке нельзя было бы верить.

Вывод и мероприятие — заготовка, а не приговор: колонки открыты на
редактирование, менеджер правит формулировку под то, что знает о рынке.

Про «спрос». Внешних данных о рынке у нас нет — ни доли, ни продаж
конкурентов. Спрос оцениваем по своим следам: сколько сделок, как растут
продажи во втором полугодии и сколько мы упустили, пока товара не было
на складе. Это спрос НА НАС, а не доля рынка, и так и подписано.
"""
from __future__ import annotations
import numpy as np
import pandas as pd

# Что складываем при свёртке группы и бренда. Всё остальное — производное
# и считается уже после, иначе получим среднее от средних.
СУММЫ = ["SKU", "Оборот", "Себест", "ВП", "Запас", "Запас_ед", "Запас_база",
         "Штук", "Строк", "Владение", "Упущено", "Дефицит", "Связок", "ЮЭ_результат",
         "Оборот_1п", "Оборот_2п", "Себест_1п", "Себест_2п",
         "ВП_1п", "ВП_2п", "Штук_1п", "Штук_2п"]


def _ц(v) -> str:
    try:
        return format(int(round(float(v))), ",d").replace(",", chr(160))
    except (TypeError, ValueError):
        return "0"


def _ч(v, зам=None):
    """Число или замена: ловит и None, и NaN, и бесконечность."""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return зам
    return зам if not np.isfinite(f) else f


def _пц(v) -> str:
    """Процент целыми. round() до int убирает «минус ноль»: рентабельность
    −0,4 % печаталась как «-0 %» и читалась как опечатка."""
    return "%d" % round(float(v))


# С какой доли одного бренда в группе это уже зависимость от поставщика,
# а не просто сильный контракт. Порог отраслевой, не расчётный.
КОНЦЕНТРАЦИЯ = 70.0


def _спрос(r) -> tuple[str, bool]:
    """Что видно про спрос и есть ли признак, что он выше наших продаж."""
    сделок = _ч(r.get("Строк"), 0) or 0
    рост = _ч(r.get("Рост_2п_%"))
    oos = _ч(r.get("OOS_%"), 0) or 0
    упущ = _ч(r.get("Упущено"), 0) or 0

    части = []
    if сделок:
        части.append("%s сделок" % _ц(сделок))
    if рост is not None:
        части.append("2п к 1п %+.0f%%" % рост)
    # Дефицит — единственный намёк на спрос ВЫШЕ того, что мы продали:
    # позиция кончалась, значит покупатель приходил и уходил ни с чем.
    голод = oos >= 20 and упущ > 0
    if голод:
        части.append("нет на складе %.0f%% времени, упущено %s ₽" % (oos, _ц(упущ)))
    return ("; ".join(части), голод)


def _вывод(r, порог_доли: float, порог_рент: float) -> tuple[str, str]:
    """Вывод по контракту и мероприятие — собираются из фактов.

    «Опорный» считаем от доли ВНУТРИ группы, а не в обороте листа: бренд
    важен относительно своей категории, с ней он и конкурирует за полку.
    Бренд с 2 % листа может держать половину небольшой группы — и в
    переговорах это ровно та цифра, от которой идёт разговор.
    """
    доля = _ч(r.get("Доля_в_группе_%"), 0) or 0
    доля_л = _ч(r.get("Доля_оборота_%"), 0) or 0
    вп = _ч(r.get("ВП"), 0) or 0
    рент = _ч(r.get("Рент_без_непрямых_%"))
    марж = _ч(r.get("Маржа_%"))
    оборот = _ч(r.get("Оборот"), 0) or 0
    сток = _ч(r.get("Запас"), 0) or 0
    дней = _ч(r.get("Дней_запаса_тек"))
    рост = _ч(r.get("Рост_2п_%"))
    текст_спроса, голод = _спрос(r)

    эк = []
    if марж is not None:
        эк.append("профит %s%%" % _пц(марж))
    if рент is not None:
        эк.append("рентабельность без непрямых %s%%" % _пц(рент))
    эк = ", ".join(эк)

    def собрать(суть, действие):
        куски = [суть] + ([эк] if эк else []) + ([текст_спроса] if текст_спроса else [])
        return ("; ".join(куски), действие)

    # Продажи по символической цене (рубль за штуку при реальной
    # себестоимости) - это списание или образец, проведённые как
    # продажа, а не рыночная цена. По периметру таких строк 228 на
    # 1,25 млн руб. искажения ВП. Без этой ветки бренд получал
    # приговор «закрыть контракт» из-за семнадцати единиц по рублю.
    себест = _ч(r.get("Себест"), 0) or 0
    if вп < 0 and себест > 1000 and оборот < 0.2 * себест:
        return собрать("продажи прошли по символической цене: оборот %s ₽ при "
                       "себестоимости %s ₽ - это не рыночная цена"
                       % (_ц(оборот), _ц(себест)),
                       "Проверить документы по этим продажам, "
                       "выводы о контракте делать после")
    if вп < 0:
        return собрать("убыточный контракт: продаём дешевле, чем покупаем",
                       "Закрыть контракт или пересмотреть закупочные цены")
    if оборот <= 0 and сток > 0:
        return собрать("продаж нет, сток лежит", "Распродать сток, не докупать")
    if рент is not None and рент < 0 and сток > 0:
        д = (", запаса на %.0f дней" % дней) if дней else ""
        return собрать("содержание запаса съедает прибыль" + д,
                       "Сократить сток; дальше возить под заказ")
    if голод and вп > 0:
        return собрать("спрос выше наших продаж, товара не хватает",
                       "Дозаказать и поднять норму запаса")
    if доля >= порог_доли:
        хорош = рент is not None and рент >= порог_рент
        return собрать("опора группы: %s%% её оборота (%.1f%% листа)" % (_пц(доля), доля_л),
                       "Делать фокус на продажи, увеличивать глубину" if хорош
                       else "Пересмотреть условия закупки и логистики")
    if рост is not None and рост >= 20 and вп > 0:
        return собрать("продажи растут", "Развивать: расширить ассортимент бренда")
    if рост is not None and рост <= -30:
        return собрать("продажи падают",
                       "Разобраться с причиной падения; сток не наращивать")
    if рент is not None and рент >= порог_рент:
        return собрать("небольшой, но рентабельный контракт",
                       "Оставить в портфеле, контролировать сток")
    if сток <= 0 and оборот > 0:
        return собрать("продаётся без склада", "Возить под заказ")
    if сток > 0 and дней is not None and дней > 365:
        return собрать("сток на год вперёд при низком спросе",
                       "Распродать сток, не докупать, оставить под заказ")
    return собрать("низкий спрос и невысокая рентабельность", "Возить под заказ")


def _вывод_группы(r, лидер: str, доля_лидера: float, контрактов: int,
                  убыточных: int, убыток_оборот: float,
                  порог_рент: float) -> tuple[str, str]:
    """Итог по всей фокус-группе. Это не контракт, и язык другой.

    На строке «общий итог» менеджер смотрит не на поставщика, а на
    категорию целиком: насколько она весома, на ком держится, окупает ли
    собственное хранение и где протекают деньги. Раньше сюда подставлялся
    тот же текст, что и для бренда, и итог по группе рассказывал про
    «крупный контракт» — читалось как ошибка.
    """
    вп = _ч(r.get("ВП"), 0) or 0
    рент = _ч(r.get("Рент_без_непрямых_%"))
    марж = _ч(r.get("Маржа_%"))
    оборот = _ч(r.get("Оборот"), 0) or 0
    сток = _ч(r.get("Запас"), 0) or 0
    дней = _ч(r.get("Дней_запаса_тек"))
    доля_л = _ч(r.get("Доля_оборота_%"), 0) or 0
    рост = _ч(r.get("Рост_2п_%"))
    текст_спроса, голод = _спрос(r)

    состав = "%s ₽ оборота, %s%% листа; контрактов %d" % (_ц(оборот), _пц(доля_л), контрактов)
    if лидер and доля_лидера:
        состав += "; лидер %s - %s%% группы" % (лидер, _пц(доля_лидера))

    эк = []
    if марж is not None:
        эк.append("профит %s%%" % _пц(марж))
    if рент is not None:
        эк.append("рентабельность без непрямых %s%%" % _пц(рент))
    if сток > 0:
        эк.append("сток %s ₽%s" % (_ц(сток), (", на %.0f дней" % дней) if дней else ""))
    if убыточных:
        эк.append("убыточных контрактов %d на %s ₽ оборота"
                  % (убыточных, _ц(убыток_оборот)))
    куски = [состав] + ([", ".join(эк)] if эк else []) \
        + ([текст_спроса] if текст_спроса else [])
    текст = "; ".join(куски)

    # Мероприятие по группе — по самой дорогой проблеме, а не по всем сразу.
    if вп < 0:
        д = "Разобрать группу по контрактам: в сумме продаём ниже закупки"
    elif рент is not None and рент < 0 and сток > 0:
        д = "Сократить сток по группе: содержание съедает всю прибыль"
    elif голод:
        д = "Поднять нормы запаса по ходовым позициям группы"
    elif доля_лидера >= КОНЦЕНТРАЦИЯ:
        д = "Зависимость от одного поставщика - проработать второго"
    elif рост is not None and рост <= -30:
        д = "Разобрать падение продаж по группе"
    elif убыточных:
        д = "Точечно разобрать убыточные контракты внутри группы"
    elif рент is not None and рент >= порог_рент:
        д = "Группа окупает себя - держать и наращивать глубину"
    else:
        д = "Держать; решения принимать точечно по контрактам"
    # Концентрация — риск, а не срочная задача, и она не должна вытеснять
    # более дорогую проблему. Но и теряться не должна: в радиаторах один
    # бренд держит 93 % группы, а мероприятием выходило «поднять нормы».
    if доля_лидера >= КОНЦЕНТРАЦИЯ and "поставщик" not in д:
        д += "; плюс риск: %s%% группы на одном поставщике (%s) - проработать второго" \
             % (_пц(доля_лидера), лидер)
    return (текст, д)


def _поля(а: str, б: str, область: str) -> tuple:
    """Где искать слово: только «Группа 1», только «Группа 2» или в обеих."""
    return (а,) if область == "г1" else (б,) if область == "г2" else (а, б)


def _зпт(v, знаков: int = 2) -> str:
    """Дробь с запятой: в русском тексте точка читается как опечатка."""
    return ("%.*f" % (знаков, float(v))).replace(".", ",")


def _фраза(части: list) -> str:
    """Склейка в предложения с заглавной буквы у каждого."""
    ч = [str(x).strip() for x in части if str(x).strip()]
    if not ч:
        return ""
    return ". ".join(s[0].upper() + s[1:] for s in ч) + "."


def _капитал(r, порог_g: float) -> str:
    """Отрабатывает ли вложенный в запас рубль своё же хранение."""
    g = _ч(r.get("GMROI"))
    if g is None:
        return ""
    как = "капитал отрабатывает" if g >= порог_g else "деньги в нём стоят дороже, чем приносят"
    return "рубль запаса возвращает %s ₽ за год при пороге %s - %s" % (
        _зпт(g), _зпт(порог_g), как)


def _комментарий(r, к: dict, шире: dict, порог_g: float, порог_рент: float) -> str:
    """Взгляд категорийщика: не «что с этой строкой», а «что с портфелем».

    «Вывод» разбирает контракт сам по себе. Здесь — то, что видно только
    сверху: какое место бренд занимает в своей категории, окупает ли
    вложенные в него деньги, есть ли в той же группе поставщик, который
    делает то же самое лучше, и не шире ли контракт одной группы. Именно
    на эти вопросы отвечает категорийный менеджер, а не на «сколько
    продали».
    """
    имя = str(r.get("Бренд") or "")
    место = к["мест"].get(имя, 0)
    всего = к["всего"]
    доля = _ч(r.get("Доля_в_группе_%"), 0) or 0
    рент = _ч(r.get("Рент_без_непрямых_%"))
    сток = _ч(r.get("Запас"), 0) or 0
    дней = _ч(r.get("Дней_запаса_тек"))
    о1, о2 = _ч(r.get("Оборот_1п"), 0) or 0, _ч(r.get("Оборот_2п"), 0) or 0

    части = []
    if место and всего:
        # Роль — это место И вес разом: третий контракт в группе не
        # «периферия», даже если его доля скромная, а десятый с большой
        # долей — не опора, а разовая крупная поставка.
        роль = ("опора категории" if место == 1 else
                "заметный контракт" if (доля >= 10 or место <= 3) else
                "второй эшелон" if доля >= 3 else "периферия ассортимента")
        части.append("%s: %d-й из %d в группе, %s%% её оборота"
                     % (роль, место, всего, _пц(доля)))
    к_ = _капитал(r, порог_g)
    if к_:
        части.append(к_)
    if сток > 0 and дней is not None and дней >= 365:
        части.append("в запасе %s ₽ - это %s дней продаж, деньги заморожены"
                     % (_ц(сток), _ц(дней)))

    # Есть ли в этой же группе поставщик, который делает то же самое лучше.
    лид, лр = к.get("лидер"), к.get("лидер_рент")
    if (лид and лид != имя and лр is not None and рент is not None
            and лр - рент >= 15 and рент < порог_рент):
        части.append("в той же группе %s работает с рентабельностью %s%% против %s%% здесь - "
                     "при пересечении номенклатуры объём логичнее переводить туда"
                     % (лид, _пц(лр), _пц(рент)))

    # Контракт шире одной группы: торг с поставщиком идёт по всему объёму.
    ш = шире.get(имя)
    if ш and ш["блоков"] > 1:
        части.append("бренд идёт ещё в %d %s на %s ₽ - условия пересматривать по всему "
                     "поставщику, а не по одной группе"
                     % (ш["блоков"] - 1, "группе" if ш["блоков"] == 2 else "группах",
                        _ц(ш["оборот"] - (_ч(r.get("Оборот"), 0) or 0))))

    # Сезонность видно только по полугодиям, и она меняет решение о закупке.
    if о1 > 0 and о2 > 0:
        д2 = 100 * о2 / (о1 + о2)
        if д2 >= 65:
            части.append("продажи смещены во второе полугодие (%s%% оборота) - "
                         "закупку планировать под этот сезон" % _пц(д2))
        elif д2 <= 25:
            части.append("продажи почти целиком в первом полугодии (%s%% оборота) - "
                         "во втором сток лежит зря" % _пц(100 - д2))
    return _фраза(части)


def _комментарий_группы(r, к: dict, порог_g: float) -> str:
    """Взгляд категорийщика на категорию целиком."""
    доля_л = _ч(r.get("Доля_оборота_%"), 0) or 0
    сток = _ч(r.get("Запас"), 0) or 0
    части = ["категория держит %s%% оборота листа и %s ₽ в стоке"
             % (_пц(доля_л), _ц(сток))]
    if к["всего"] and к["к80"]:
        хвост = к["всего"] - к["к80"]
        части.append("80%% оборота дают %d %s из %d"
                     % (к["к80"], "контракт" if к["к80"] == 1 else "контрактов", к["всего"])
                     + ("; остальные %d занимают полку и оборотные средства" % хвост
                        if хвост > 0 else ""))
    к_ = _капитал(r, порог_g)
    if к_:
        части.append(к_)
    if к["не_отраб"]:
        части.append("%d %s не окупают собственное хранение, в них %s ₽ запаса - "
                     "это первый источник высвобождения денег"
                     % (к["не_отраб"], "контракт" if к["не_отраб"] == 1 else "контрактов",
                        _ц(к["запас_не_отраб"])))
    return _фраза(части)


def _фокус(г1: str, г2: str, слова: list[str], исключения: dict,
           область: dict) -> str:
    """К какой фокус-группе отнести строку.

    Берём ПЕРВОЕ подошедшее слово: группа вроде «Насосное оборудование и
    баки мембранные» подходит и под «насос», и под «бак», а строка должна
    лежать ровно в одном блоке, иначе оборот задвоится в итогах. Поэтому
    порядок слов в настройках — это приоритет, а не просто список.

    Область поиска задаётся на слово. «Бойлеры» и «водонагреватели» ищем
    только в «Группа 1»: марка бака («Нержавеющий бак») стоит в «Группа 2»
    и к типу товара отношения не имеет.

    Исключения — когда слово подошло, а товар не тот. «радиатор» ловит
    «Арматуру радиаторную» (клапаны, головки, узлы подключения) и
    «Масляные радиаторы» (обогреватели): в своде по радиаторам они давали
    лишние 3,95 млн ₽ оборота. Исключённая строка не пропадает молча — она
    пробует следующие слова и, если ни одно не подошло, в лист не попадает.
    """
    а, б = str(г1 or "").lower(), str(г2 or "").lower()
    for с in слова:
        поля = _поля(а, б, область.get(с, "оба"))
        if not any(с in п for п in поля):
            continue
        нет = исключения.get(с) or ()
        if any(str(x).lower() in п for x in нет for п in поля):
            continue
        return с
    return ""


def _производные(t: pd.DataFrame, годовой: float, общий: float,
                 порог_оборота: float = 0.0, порог_базы: float = 0.0) -> pd.DataFrame:
    """Доли и проценты считаем ПОСЛЕ сложения — иначе среднее от средних."""
    t = t.copy()
    # GMROI — сколько валовой прибыли за год приносит рубль, вложенный
    # в запас. Знаменатель тот же, от которого считается стоимость
    # владения: средний запас за период. Ниже 0,566 (ставка владения)
    # контракт не окупает собственного хранения.
    _б = (t["Запас_база"] if "Запас_база" in t.columns else t["Запас"]).astype(float)
    t["GMROI"] = (t["ВП"] * годовой) / _б.where(_б >= max(порог_базы, 1.0))
    t["Доля_оборота_%"] = 100 * t["Оборот"] / (общий or 1.0)
    поло = t["Оборот"] > 0
    t["Маржа_%"] = np.where(поло, 100 * t["ВП"] / t["Оборот"].where(поло), np.nan)
    # Рентабельности делят ГОДОВУЮ величину на оборот периода. Когда оборот
    # копеечный, а строка попала в лист по стоку, отношение улетает: было
    # −122 024 % и +5 829 %. Такое число не «очень плохо» и не «очень
    # хорошо», оно просто ни о чём — на копеечном обороте рентабельности нет.
    значимо = поло & (t["Оборот"] >= порог_оборота)
    об_год = (t["Оборот"] * годовой).where(значимо)
    t["Рент_без_непрямых_%"] = 100 * (t["ВП"] * годовой - t["Владение"]) / об_год
    if "ЮЭ_результат" in t.columns:
        # Выгрузка юнит-экономики сделана за ПЕРВОЕ ПОЛУГОДИЕ (202601—202606),
        # а наш оборот — за девять месяцев. Делить полугодовой результат на
        # годовой оборот нельзя: получается смесь двух периодов, и знаменатель
        # завышен примерно в 1,7 раза. Делим на оборот того же полугодия.
        _1п = t["Оборот_1п"] if "Оборот_1п" in t.columns else t["Оборот"]
        t["ЮЭ_рентабельность_%"] = (100 * t["ЮЭ_результат"]
                                    / _1п.where(_1п >= порог_оборота))
    t["OOS_%"] = np.where(t["Связок"] > 0, 100 * t["Дефицит"] / t["Связок"].replace(0, np.nan),
                          np.nan) if "Связок" in t.columns else np.nan
    t["Рост_2п_%"] = np.where(t["Оборот_1п"] > 0,
                              100 * (t["Оборот_2п"] / t["Оборот_1п"].replace(0, np.nan) - 1),
                              np.nan)
    сут = t["Себест"] / 365.0 * годовой
    t["Дней_запаса_тек"] = (t["Запас"] / сут.replace(0, np.nan)).clip(upper=3650)
    return t


