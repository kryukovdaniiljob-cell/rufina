def _заключение(д, S, л2, эп, порог):
    д.структурный("Заключение")
    д.абзац("Отчёт категорийной аналитики отвечает на три вопроса: где "
            "деньги работают, где они лежат и что с этим делать по каждой "
            "позиции поимённо. Доклад по нему занимает десять минут и "
            "строится на пяти листах.")
    gm = _ч(S.get("gmroi"))
    if gm >= порог:
        д.абзац("Портфель в целом окупает содержание: отдача на рубль запаса "
                "%s против порога %s, прибыль за вычетом содержания %s руб. "
                "в год." % (_зпт(gm), _зпт(порог), _р(S.get("эконом_прибыль"))))
    else:
        д.абзац("Портфель не окупает содержания: отдача на рубль запаса %s "
                "против порога %s. Это главный вывод доклада."
                % (_зпт(gm), _зпт(порог)))
    if л2 is not None and эп and len(л2):
        мин = л2[л2[эп] < 0]
        if len(мин):
            имя = _кол(л2, "Товарное направление", "Наименование")
            д.абзац("Направлений с отрицательным результатом: %d, суммарно "
                    "они забирают %s руб. в год и держат %s руб. запаса. "
                    "Крупнейшее — «%s»."
                    % (len(мин), _р(abs(_ч(мин[эп].sum()))),
                       _р(мин[_кол(л2, "Запас")].sum()),
                       мин.sort_values(эп).iloc[0].get(имя)))
    д.абзац("Главный риск доклада — не ошибка в расчёте, а неверное "
            "толкование корректной цифры. Поэтому оговорки о природе "
            "эффекта, о периоде юнит-экономики, о составе листа брендов и о "
            "способе распределения упущенных продаж следует произносить "
            "самостоятельно, не дожидаясь вопроса.")


