    д.подраздел("Лист «09.Типы складов» — цена полки")
    if тс is not None and len(тс):
        имя = _кол(тс, "Тип склада")
        зп = _кол(тс, "Запас")
        эп2 = _кол(тс, "Эконом_прибыль")
