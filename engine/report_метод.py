    д.абзац("Лист открывается при любом сомнении в достоверности. "
            "Формулировка: «%d проверок, расхождений нет. Пять из них "
            "сверяют отчёт напрямую с выгрузкой — сходится до рубля»." % n)
    д.абзац("Лист «00b.Логика» содержит формулу и порог каждого показателя: "
            "ставку стоимости владения, порог GMROI, границы сегментов, "
            "коэффициент возврата покупателя, порог существенности запаса.")


