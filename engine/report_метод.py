def _листы_ответов(д, св, списки, S, оф, тс, порог):
    д.раздел("Листы для ответов на вопросы")
    д.абзац("Семь листов не входят в основной доклад, но открываются по "
            "конкретному вопросу.")
    д.таблица("Листы для ответов на типовые вопросы",
              ["Вопрос", "Лист", "Что содержит"],
              [["Какой город хуже всех?", "08b.Офисы", "Разрез по офисам"],
               ["Сколько стоит полка?", "09.Типы складов",
                "Основной, Cash and Carry, РЦ, витрина"],
               ["А по конкретному складу?", "02.По складам", "Дерево до позиции"],
               ["С каким поставщиком говорить?", "32.Поставщики",
                "Отдача на рубль запаса"],
               ["Что крупное надо решить?", "0a.Решения по портфелю",
                "Бренды, направления, склады"],
               ["Что говорит юнит-экономика?", "28.Сверка решений",
                "Согласие и расхождения"],
               ["Откуда эта цифра?", "00b.Логика", "Формула каждого показателя"]],
              ширины=[55, 45, 65])

    # ------------------------------------------------ офисы
    д.подраздел("Лист «08b.Офисы» — сравнение городов")
    if оф is not None and len(оф):
        имя = _кол(оф, "Офис")
        зп = _кол(оф, "Запас")
