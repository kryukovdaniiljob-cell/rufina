def _руководству(д, S, л2, эп, оф, зад, пф):
    д.раздел("Доклад руководству")
    д.абзац("Руководству дивизиона докладываются три тезиса. Больше не "
            "требуется: каждый дополнительный тезис снижает вероятность "
            "решения по первым трём.")

    # тезис 1 — разрыв в продажах против плана работ
    д.подраздел("Тезис первый: соотношение дыры в продажах и дыры в запасе")
    п = _план(пф)
    отст = (п["план_полные"] - п["факт_полные"]) if п else 0.0
    кэ = _кол(зад, "Эффект за год, ₽") if зад is not None else None
    эфф = _ч(зад[кэ].sum()) if кэ else 0.0
    if отст > 0 and эфф > 0:
        д.абзац("Отставание от плана за завершённые месяцы составляет %s руб. "
                "Весь план работы с запасом даёт %s руб. в год, то есть %s %% "
                "от величины отставания."
                % (_р(отст), _р(эфф), пц(100 * эфф / отст)))
        д.абзац("Запрашиваемое решение: рассмотрение вопроса о спросе и "
                "ценообразовании, а не только о складских остатках.")
    else:
        д.абзац("План работы с запасом даёт %s руб. в год. Отставание от "
                "плана продаж в текущем расчёте не выделено." % _р(эфф))

    # тезис 2 — самая слабая площадка
    д.подраздел("Тезис второй: где заперт капитал")
    if оф is not None and len(оф):
        имя = _кол(оф, "Офис")
        зп = _кол(оф, "Запас")
        эп2 = _кол(оф, "Эконом_прибыль")
        сл = оф.sort_values(эп2).iloc[0]
        лу = оф.sort_values(эп2, ascending=False).iloc[0]
        доля = 100 * _ч(сл.get(зп)) / max(_ч(S.get("запас")), 1)
        д.абзац("Офис «%s» держит %s руб. запаса — %s %% запаса периметра — "
                "при обороте %s руб. Прибыль за вычетом содержания "
                "составляет %s руб. в год."
                % (сл.get(имя), _р(сл.get(зп)), пц(доля), _р(сл.get("Оборот")),
                   _р(сл.get(эп2))))
        д.абзац("Для сравнения: офис «%s» при запасе %s руб. даёт %s руб. "
                "прибыли. Разница в результате — %s руб. в год."
                % (лу.get(имя), _р(лу.get(зп)), _р(лу.get(эп2)),
                   _р(_ч(лу.get(эп2)) - _ч(сл.get(эп2)))))

    # тезис 3 — природа эффекта
    д.подраздел("Тезис третий: природа заявленного эффекта")
    д.абзац("Этот тезис следует произнести самостоятельно, не дожидаясь "
            "вопроса от финансовой службы.")
    if зад is not None and кэ:
        ки = _кол(зад, "Источник эффекта", "Из чего эффект")
        if ки:
            по_и = зад.groupby(ки)[кэ].sum().sort_values(ascending=False)
            ДЕНЬГИ = ("прекращение", "возврат", "прибыль")
            строки = []
            жив = усл = 0.0
            for и, v in по_и.items():
                живые = any(k in str(и).lower() for k in ДЕНЬГИ)
                жив += v if живые else 0
                усл += 0 if живые else v
                строки.append([str(и)[:46], _р(v),
                               "Живые деньги" if живые
                               else "Расчётная ставка, не выручка"])
            д.таблица("Природа заявленного эффекта",
                      ["Источник эффекта", "Сумма, руб./год", "Природа"],
                      строки, ширины=[65, 35, 65], право=(1,))
            всего = жив + усл
            if всего:
                д.абзац("Живыми деньгами приходит %s руб. из %s, то есть "
                        "%s %%. Остальное — прекращение расходов на хранение "
                        "и стоимость капитала: величина реальная, но "
                        "проявляется в высвобождении оборотных средств, "
                        "а не в кассе."
                        % (_р(жив), _р(всего), пц(100 * жив / всего)))


