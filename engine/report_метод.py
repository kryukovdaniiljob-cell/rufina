def _рабочие(д, списки, S):
    д.раздел("Рабочие листы")
    д.абзац("Пятнадцать листов служат для подготовки доклада и выполнения "
            "задач, но на экран не выводятся.")
    д.подраздел("Списки действий")
    СП = [("23.Вывести", "вывести"), ("24.Новинки", "новинки"),
          ("25.Медленные", "медленные"), ("25b.Пересмотр закупки", "закупка"),
          ("26.Развивать", "развивать"), ("27.Переместить", "переместить")]
    строки = []
    for лист, ключ in СП:
        б = S.get(ключ) or {}
        if not isinstance(б, dict):
            continue
        строки.append([лист, цел(б.get("sku") or б.get("позиций") or 0),
                       _р(б.get("запас")), _р(б.get("владение"))])
    if строки:
        д.таблица("Рабочие списки действий",
                  ["Лист", "Позиций", "Запас, руб.", "Содержание, руб./год"],
                  строки, ширины=[55, 25, 45, 45], право=(1, 2, 3))
    д.абзац("Содержательные пояснения к спискам:")
    д.список([
        "«23.Вывести» — запас есть, продаж нет, партия старше порога новизны;",
        "«24.Новинки» — запас есть, продаж нет, но товар молодой; новинкой "
        "считается позиция, у которой и старейшая партия моложе порога;",
        "«25.Медленные» — продажи идут, но запаса больше нормы по дням; "
        "основной источник задач на уценку;",
        "«25b.Пересмотр закупки» — избыток образовался недавно, лечится не "
        "уценкой, а размером следующей партии;",
        "«26.Развивать» — класс A или B, высокий дефицит и достаточная "
        "маржа: спрос выше наших продаж;",
        "«27.Переместить» — лежит без спроса на одном складе при дефиците на "
        "другом; перевозится только свободный остаток, резерв исключён.",
    ])
    д.подраздел("Справочные разрезы")
    д.абзац("Листы «06.Бренды», «10.Склады», «11.Направление x Склад», "
            "«12.Группа1 x Склад», «13.Бренд x Склад» содержат одни и те же "
            "показатели в разных разрезах и используются для поиска "
            "конкретной цифры перед совещанием.")
    д.абзац("Лист «18.SKU полный» — основа всего расчёта: %s строк, по одной "
            "на позицию. Выводить на экран не следует: обсуждение немедленно "
            "уходит в отдельные позиции." % _р(S.get("sku")))


