def _дерево_строк(св, слои):
    """Плоский список (уровень, путь, строка) в порядке обхода дерева."""
    узлы = {}
    for имя, ключи in слои:
        if имя not in св:
            continue
        df = св[имя]
        ключи = [k for k in ключи if k in df.columns]
        for _, r in df.iterrows():
            путь = tuple(str(r[k]) for k in ключи if pd.notna(r[k]))
            if путь and путь not in узлы:
                узлы[путь] = r
    дети = {}
    for п in узлы:
        дети.setdefault(п[:-1], []).append(п)
    out = []

    def обход(род, ур):
        сп = sorted(дети.get(род, []),
                    key=lambda p: -float(узлы[p].get("Оборот") or 0))
        for п in сп:
            out.append((ур, п, узлы[п]))
            обход(п, ур + 1)
    обход(tuple(), 0)
    return out


