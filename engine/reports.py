def лист_брендов(W, wb, t, S, форматы, созданные, лог=print):
    """Бренды внутри фокус-групп, двумя уровнями со сворачиванием."""
    if t is None or not len(t):
        return
    Fh, Ft, Fn, F2, Fp = (форматы["h"], форматы["t"], форматы["n"],
                          форматы["2"], форматы["p"])
    ws = wb.add_worksheet("0г.Бренды по группам")
    W.sheets["0г.Бренды по группам"] = ws
    созданные.append("0г.Бренды по группам")
    Fт = wb.add_format({"bold": True, "font_size": 12, "font_name": "Arial",
                        "font_color": "#1F3864"})
    ws.write(0, 0, "БРЕНДЫ ПО ГРУППАМ. Бренд внутри группы — это контракт с поставщиком, и он НЕ дробится по подгруппам. Строки группы сворачиваются плюсом слева. «Вывод» и «Мероприятия» — заготовка, правьте под то, что знаете о рынке", Fт)

    кол = list(t.columns)
    шапка = 2
    # Проценты пишем долей: формат ячейки сам добавит знак.
    for j, c in enumerate(кол):
        ws.write(шапка, j, c, Fh)
        ф = Fp if c in БРЕНДЫ_ПРОЦ else (Ft if t[c].dtype == object else Fn)
        ws.set_column(j, j, БРЕНДЫ_ШИРИНЫ.get(c, 14), ф)

    Fгр = wb.add_format({"bold": True, "font_name": "Arial", "font_size": 9,
                         "bg_color": "#EDF1F7"})
    Fбр = wb.add_format({"font_name": "Arial", "font_size": 9, "indent": 1})
    for i, (_, r) in enumerate(t.iterrows(), start=шапка + 1):
        ур = int(r.get("Уровень") or 2)
        ws.write(i, 0, str(r.get("Наименование") or ""), Fгр if ур == 1 else Fбр)
        for j, c in enumerate(кол):
            if j == 0:
                continue
            v = r.get(c)
            if c in БРЕНДЫ_ПРОЦ:
                ws.write(i, j, (float(v) / 100 if pd.notna(v) else None), Fp)
            elif isinstance(v, str) or pd.isna(v):
                ws.write(i, j, "" if pd.isna(v) else str(v), Ft)
            else:
                ws.write_number(i, j, float(v), Fn)
        # Бренды прячем под группу: открывается плюсом слева.
        if ур == 2:
            ws.set_row(i, None, None, {"level": 1, "hidden": True})

    n = len(t)
    ws.outline_settings(True, False, True, False)
    ws.freeze_panes(шапка + 1, 1)
    ws.autofilter(шапка, 0, шапка + n, len(кол) - 1)
    if "Профит (маржа)" in кол:
        м = кол.index("Профит (маржа)")
        ws.conditional_format(шапка + 1, м, шапка + n, м,
            {"type": "cell", "criteria": "<", "value": 0,
             "format": wb.add_format({"bg_color": "#FFC7CE", "font_color": "#9C0006",
                                      "num_format": "0%", "font_name": "Arial",
                                      "font_size": 9})})
    if "Рентабельность без непрямых затрат" in кол:
        р = кол.index("Рентабельность без непрямых затрат")
        ws.conditional_format(шапка + 1, р, шапка + n, р,
            {"type": "cell", "criteria": "<", "value": 0,
             "format": wb.add_format({"bg_color": "#FFC7CE", "font_color": "#9C0006",
                                      "num_format": "0%", "font_name": "Arial",
                                      "font_size": 9})})
    _печать(ws, "Бренды по группам · данные на %s" % S["дата"], альбом=True, повтор=True)
    лог("   Лист «0г.Бренды по группам»: %d строк, свёрнут до групп" % n)
