def простой_лист(W, wb, имя, df, форматы, созданные, ширины=None, порог=None, лог=print,
                 заголовок=None):
    """Лист из готовой таблицы: денежные и процентные колонки форматируются сами."""
    if df is None or not len(df):
        return
    Fh, Ft, Fn, F2, Fp = форматы["h"], форматы["t"], форматы["n"], форматы["2"], форматы["p"]
    x = df.copy()
    for c in x.columns:
        if c in ПРОЦЕНТНЫЕ:
            x[c] = pd.to_numeric(x[c], errors="coerce") / 100.0
    сдвиг = 1 if заголовок else 0
    x.to_excel(W, sheet_name=имя, index=False, startrow=1 + сдвиг, header=False)
    ws = W.sheets[имя]; созданные.append(имя)
    if заголовок:
        ws.write(0, 0, заголовок, wb.add_format(
            {"bold": True, "font_size": 11, "font_name": "Arial", "font_color": "#1F3864"}))
    for j, c in enumerate(x.columns):
        ws.write(сдвиг, j, ЗАГОЛОВКИ.get(c, str(c)), Fh)
        if c in ПРОЦЕНТНЫЕ:      ш, f = 12, Fp
        elif c == "GMROI":       ш, f = 10, F2
        elif c in ДЕНЕЖНЫЕ:      ш, f = 15, Fn
        elif x[c].dtype.kind in "if": ш, f = 12, Fn
        else:                    ш, f = (ширины or {}).get(c, 26), Ft
        ws.set_column(j, j, ш, f)
    n = len(x)
    ws.freeze_panes(1 + сдвиг, 1); ws.autofilter(сдвиг, 0, n + сдвиг, len(x.columns) - 1)
    if порог is not None and "GMROI" in x.columns:
        gi = list(x.columns).index("GMROI")
        ws.conditional_format(1 + сдвиг, gi, n + сдвиг, gi, {"type": "cell", "criteria": "<",
            "value": порог, "format": wb.add_format({"bg_color": "#FFC7CE", "font_color": "#9C0006",
                                                     "num_format": "#,##0.00", "font_name": "Arial",
                                                     "font_size": 9})})
    for кол in ("Эконом_прибыль", "Разница", "Цель_ВП"):
        if кол in x.columns:
            ci = list(x.columns).index(кол)
            ws.conditional_format(1 + сдвиг, ci, n + сдвиг, ci, {"type": "cell", "criteria": "<",
                "value": 0, "format": wb.add_format({"font_color": "#9C0006", "num_format": "#,##0",
                                                     "font_name": "Arial", "font_size": 9})})
    _печать(ws, имя + " · данные по " + "", альбом=True, повтор=True)


