    # Статус выполнения — выпадающий список, а не свободный текст:
    # иначе по колонке нельзя ни отобрать, ни посчитать.
    if "Статус выполнения" in зд.columns:
        си = list(зд.columns).index("Статус выполнения")
        ws.data_validation(шапка + 1, си, шапка + n, си,
                           {"validate": "list", "source": СТАТУСЫ_ВЫПОЛНЕНИЯ,
                            "input_title": "Статус", "input_message": "Выберите из списка"})
        for цвет, слово in (("#C6EFCE", "Выполнено"), ("#DDEBF7", "В работе"),
                            ("#F2F2F2", "Отклонено"), ("#FCE4D6", "Отложено")):
            ws.conditional_format(шапка + 1, си, шапка + n, си,
                {"type": "cell", "criteria": "==", "value": chr(34) + слово + chr(34),
                 "format": wb.add_format({"bg_color": цвет, "font_name": "Arial",
                                          "font_size": 9})})
    ws.set_landscape(); ws.set_paper(9); ws.fit_to_pages(1, 0)
    ws.repeat_rows(шапка)
    лог("   Лист «0.Задачи»: %d строк, свёрнуто до приоритетов 1–2" % n)


